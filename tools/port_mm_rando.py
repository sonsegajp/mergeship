def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def enum_body(text, name):
    end = re.search(r'\}\s*' + name + r'\s*;', text)
    if not end:
        sys.exit('port_mm_rando: enum %s not found' % name)
    start = text.rfind('typedef enum', 0, end.start())
    body = text[text.index('{', start) + 1:end.start()]
    # Preprocessor lines inside an enum (MergeShip2's X-macro include of MsItems.def) are not enumerators.
    body = chr(10).join(l for l in strip_comments(body).splitlines() if not l.strip().startswith('#'))
    return [e.split('=')[0].strip() for e in body.split(',') if e.strip()]


def readable(enum_name, prefix):
    words = enum_name[len(prefix):].split('_')
    out = []
    for w in words:
        out.append(w if w.isdigit() else w.capitalize())
    return ' '.join(out)


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


