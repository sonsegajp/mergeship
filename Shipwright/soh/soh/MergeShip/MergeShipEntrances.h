// entrance.cpp, AreEntrancesCompatible: an entrance of Termina must not lead back into its own Majora's Mask scene
// (Termina's regions have no Ocarina of Time scene for SoH's own check). The moon's warps may (a moon child to the field).
bool MergeShip_Entrances_SameTerminaScene(const Rando::Entrance* entrance, const Rando::Entrance* target);
// MergeShipTerminaLogic.cpp, MergeShip_TerminaLogic_PropagateTime: of the MM time slices `slices` reaching a shuffled
// exit of Termina, those at which it lets the player through -- its own condition holds at that slice (a door with MM
// opening hours), and, when a house, shop or other interior of Termina that has opening hours is now behind it, that
// interior's own door would be open too (its NPCs keep their schedules wherever the door is). Each slice is evaluated
// on its own (the current time is restored). Any other exit: `slices` unchanged.
uint64_t MergeShip_Entrances_OpenTime(const Rando::Entrance& exit, uint64_t slices);
// entrance.cpp, ValidateWorld (the final one, after every pool is placed): false when the world link moved, a
// Termina entrance is connected to nothing, or the seed would need more overrides than the table holds.
bool MergeShip_Entrances_ValidateWorld();
// fill.cpp, Fill: the generation attempts of a seed. An attempt that failed (entrances: the entrance shuffle; else the
// item placement or an unbeatable result) is counted; when all of them failed in a unified seed, one clear error names
// the options (SPDLOG_ERROR, and MergeShip_Entrances_LastFailure for the test harness's randoer).
void MergeShip_Entrances_BeginFill();
void MergeShip_Entrances_AttemptFailed(bool entrances);
void MergeShip_Entrances_FillFailed();
const std::string& MergeShip_Entrances_LastFailure();
// MergeShip_Termina_WrapSeed: MERGESHIP_SEED["entrances"] from the SoH spoiler's "entrances" (MsEntrances.h).
nlohmann::ordered_json MergeShip_Entrances_SeedSection(const nlohmann::ordered_json& ootSpoiler);

// Test harness: fill the runtime table from the last generated seed (as Entrance_Init does for a loaded file), and a
// summary of the Termina entrances of that seed.
void MergeShip_Entrances_LoadTableFromContext();
std::vector<std::string> MergeShip_Entrances_Summary();
// MergeShipTest.cpp: randoer, ertable, ertake (see MergeShipEntrances.cpp). False for any other command.
bool MergeShip_Entrances_TestCommand(const std::string& op, const std::vector<std::string>& args);
