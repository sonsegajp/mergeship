def listing(trows, prows, mm_gi):
    gi = {r['gid']: r for r in mm_gi}
    out = ['Termina items that can appear in Hyrule (SoH, RG_MM_* generated by port_mm_rando.py): model = MM\'s',
           '(MergeShip_DrawGiTerminaItem, soh/MergeShip/MergeShipTerminaGiDraw.cpp)']
    for t in trows:
        if t['kind'] == 'MMGid':
            r = gi.get(t['gid'])
            model = 'MM %s (GetItem_Draw%s: %s)' % (t['gid'], r['func'], ', '.join(x[0] for x in r['res'] if x))
        elif t['kind'] in ('DrawSmallKey', 'DrawBossKey'):
            model = "MM %s, MM's own key  [2Ship's per-dungeon emblem key is 2ship.o2r's, which SoH does not mount]" % \
                t['gid']
        elif t['kind'] == 'DrawSkulltulaToken':
            model = 'MM GID_SKULL_TOKEN_2 (object_st gSkulltulaTokenDL + flame), MM\'s own flame colour'
        else:
            model = "2Ship's %s (MM models from mm.o2r)" % t['kind']
        out.append('  %-34s %-26s %s' % (t['rg'], t['ri'], model))
    enums = strip_comments(read(os.path.join(SOH_RANDO, 'randomizerEnums', 'RandomizerGet.h')))
    drawn = dict(re.findall(r'itemTable\[(RG_\w+)\]\.SetCustomDrawFunc\((\w+)\)',
                            read(os.path.join(SOH_RANDO, 'item_list.cpp'))))
    generated = {t['rg'] for t in trows}
    older = [rg for rg in re.findall(r'RANDO_ENUM_ITEM\((RG_\w+)', enums)
             if (rg.startswith('RG_MM_') or '_MM_' in rg or rg == 'RG_PROGRESSIVE_GORON_LULLABY') and rg not in generated]
    out += ['', "Majora's Mask items SoH carried before the port (masks, equipment, songs, quest items, stray fairies;",
            "RandomizerGet.h): model = MM's, each by its own MergeShip draw function (item_list.cpp)"]
    for rg in older:
        out.append('  %-34s %s' % (rg, drawn.get(rg, 'NONE (falls back)')))
    out += ['', 'Hyrule items that can appear in Termina (2Ship, proxies RI_OOT_*): model = OoT\'s',
            '(Rando::MergeShip::DrawProxy -> MergeShip_OoTGi_DrawKey, 2s2h/Rando/MergeShip/OoTGiDraw.cpp)']
    for p in prows:
        if p['kind'] == 'OoTGid':
            model = 'OoT %s%s' % (p['gid'], '' if p['tint'] == 'None' else ' (%s tint)' % p['tint'])
        elif p['kind'] == 'MMGid':
            model = 'MM %s' % p['gid']
        else:
            model = p['kind']
        if p['note']:
            model += '  [%s]' % p['note']
        out.append('  RI_OOT_%-38s %s' % (p['key'], model))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--list', action='store_true')
    args = ap.parse_args()

    mm_gi = parse_mm_draw()
    trows, problems = termina_rows(mm_gi)
    soh_text, p2 = gen_soh(mm_gi, trows)
    problems += p2
    oot_gi, _ = parse_oot_draw()
    prows, p3 = proxy_rows(oot_gi)
    problems += p3
    ship_text = gen_2ship(oot_gi, prows)

    if args.list:
        print('\n'.join(listing(trows, prows, mm_gi)))
    print('gen_cross_gi: %d MM get-item rows, %d Termina items in Hyrule; %d OoT get-item rows, %d Hyrule proxies' %
          (len(mm_gi), len(trows), len(oot_gi), len(prows)))
    kinds = collections.Counter(t['kind'] for t in trows)
    print('gen_cross_gi: Termina draws: %s' % ', '.join('%d %s' % (n, k) for k, n in kinds.most_common()))
    pk = collections.Counter(p['kind'] for p in prows)
    print('gen_cross_gi: proxy draws: %s (%d approximations, see --list)' %
          (', '.join('%d %s' % (n, k) for k, n in pk.most_common()), sum(1 for p in prows if p['note'])))
    for p in problems:
        print('  PROBLEM (falls back to a rupee): ' + p)
    n_rg, n_proxy, fallbacks = audit(trows, prows)
    print('gen_cross_gi: audit: %d Majora\'s Mask RandomizerGets in SoH, %d proxies in 2Ship, %d falling back' %
          (n_rg, n_proxy, len(fallbacks)))
    for f in fallbacks:
        print('  FALLBACK: ' + f)
    problems += fallbacks
    sites = audit_draw_sites()
    print('gen_cross_gi: draw sites: %d checked (held up, chests, lying / dropped, shop shelves in both games), %d broken' %
          (len(DRAW_SITES), len(sites)))
    for f in sites:
        print('  FALLBACK: ' + f)
    problems += sites

    stale = 0
    for path, text in ((OUT_SOH, soh_text), (OUT_2SHIP, ship_text)):
        old = read(path) if os.path.exists(path) else None
        if old == text:
            continue
        if args.check:
            print('  STALE: %s' % os.path.relpath(path, ROOT))
            stale += 1
        else:
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            print('gen_cross_gi: wrote %s' % os.path.relpath(path, ROOT))
    return 1 if (problems or stale) else 0


if __name__ == '__main__':
    sys.exit(main())
