def parse_mm():
    d = Data()
    types = read(os.path.join(MM, 'Types.h'))
    d.check_ids = [c for c in enum_body(types, 'RandoCheckId') if c not in ('RC_UNKNOWN', 'RC_MAX')]
    d.check_types = [c for c in enum_body(types, 'RandoCheckType') if c != 'RCTYPE_MAX']
    d.item_ids = enum_body(types, 'RandoItemId')
    d.region_ids = [r for r in enum_body(types, 'RandoRegionId') if r != 'RR_MAX']
    d.option_ids = [o for o in enum_body(types, 'RandoOptionId') if o != 'RO_MAX']
    d.option_enums = {name: enum_body(types, name) for name in set(ENUM_OPTIONS.values())}
    enum_values = {}
    for name in list(d.option_enums) + ['RandoOptionGenericOffOn', 'RandoOptionGenericNoYes']:
        for i, e in enumerate(enum_body(types, name)):
            enum_values[e] = i

    checks = read(os.path.join(MM, 'StaticData', 'Checks.cpp'))
    d.checks = collections.OrderedDict()
    for m in re.finditer(r'\bRC\((RC_\w+),\s*(RCTYPE_\w+),\s*(SCENE_\w+),\s*(FLAG_\w+),\s*([^,]+?),\s*(RI_\w+)\)',
                         checks):
        if m.group(1) == 'RC_UNKNOWN':
            continue
        d.checks[m.group(1)] = {'type': m.group(2), 'scene': m.group(3), 'item': m.group(6)}
    missing = [c for c in d.check_ids if c not in d.checks]
    if missing:
        sys.exit('port_mm_rando: checks without a Checks.cpp row: %s' % missing[:10])

    # Each native RandoItemId's RandoItemType (its container look). The proxies' rows are macros, not matched here.
    items = read(os.path.join(MM, 'StaticData', 'Items.cpp'))
    d.item_types = dict(re.findall(r'\bRI\((RI_\w+),\s*"(?:[^"\\]|\\.)*",\s*"(?:[^"\\]|\\.)*",\s*(RITYPE_\w+)', items))

    options = read(os.path.join(MM, 'StaticData', 'Options.cpp'))
    d.options = collections.OrderedDict()
    for m in re.finditer(r'\bRO\((RO_\w+),\s*([^)]+?)\)', options):
        name, default = m.group(1), m.group(2).strip()
        if default.isdigit():
            value = int(default)
        elif default in enum_values:
            value = enum_values[default]
        elif default in SYMBOLS:
            value = SYMBOLS[default]
        else:
            sys.exit('port_mm_rando: unknown default %s for %s' % (default, name))
        d.options[name] = value
    # The unified randomizer's defaults (UNIFIED_DEFAULTS), as values of the same kind.
    d.unified_defaults = collections.OrderedDict()
    for name, value in d.options.items():
        u = UNIFIED_DEFAULTS.get(name, value)
        if isinstance(u, str):
            if u not in enum_values:
                sys.exit('port_mm_rando: unknown unified default %s for %s' % (u, name))
            u = enum_values[u]
        d.unified_defaults[name] = u
    d.enum_values = enum_values

    # Regions: the checks each lists (2Ship's pools take only checks some region lists), and their scene.
    d.region_checks = collections.OrderedDict()
    d.region_scene = {}
    sources = sorted(os.listdir(os.path.join(MM, 'Logic', 'Regions')))
    texts = [read(os.path.join(MM, 'Logic', 'Regions', f)) for f in sources if f.endswith('.cpp')]
    texts.append(read(os.path.join(MM, 'Logic', 'Logic.cpp')))
    for text in texts:
        text = strip_comments(text)
        starts = [m for m in re.finditer(r'Regions\[(RR_\w+)\]\s*=\s*RandoRegion\s*\{', text)]
        for i, m in enumerate(starts):
            end = starts[i + 1].start() if i + 1 < len(starts) else len(text)
            body = text[m.end():end]
            region = m.group(1)
            sm = re.search(r'\.sceneId\s*=\s*(SCENE_\w+)', text[m.start():end])
            d.region_scene[region] = sm.group(1) if sm else 'SCENE_MAX'
            d.region_checks.setdefault(region, [])
            for cm in re.finditer(r'\bCHECK\((RC_\w+)', body):
                if cm.group(1) not in d.region_checks[region]:
                    d.region_checks[region].append(cm.group(1))
    d.home_region = {}
    for region, cks in d.region_checks.items():
        for c in cks:
            d.home_region.setdefault(c, region)
    return d


def parse_def():
    text = read(DEF)
    rows = []
    for m in re.finditer(r'^MS_ITEM\((\w+),\s*(RG_\w+),\s*(RI_\w+),\s*(MS_KIND_\w+),\s*(MS_\w+),\s*(\d),\s*(\d),'
                         r'\s*(\d+),\s*"((?:[^"\\]|\\.)*)"\)', text, re.M):
        rows.append({'key': m.group(1), 'rg': m.group(2), 'ri': m.group(3), 'kind': m.group(4), 'persist': m.group(5),
                     'oot': int(m.group(6)), 'mm': int(m.group(7)), 'max': int(m.group(8)), 'name': m.group(9),
                     'proxy': False})
    for m in re.finditer(r'^MS_ITEM_OOT\((\w+),\s*(RG_\w+),\s*(MS_KIND_\w+),\s*(MS_\w+),\s*(\d),\s*(\d),'
                         r'\s*(\d+),\s*"((?:[^"\\]|\\.)*)"\)', text, re.M):
        rows.append({'key': m.group(1), 'rg': m.group(2), 'ri': 'RI_OOT_' + m.group(1), 'kind': m.group(3),
                     'persist': m.group(4), 'oot': int(m.group(5)), 'mm': int(m.group(6)), 'max': int(m.group(7)),
                     'name': m.group(8), 'proxy': True})
    aliases = re.findall(r'^MS_ALIAS_RG\((RG_\w+),\s*(\w+)\)', text, re.M)
    skip_rg = re.findall(r'^MS_SKIP_RG\((RG_\w+),', text, re.M)
    skip_ri = re.findall(r'^MS_SKIP_RI\((RI_\w+),', text, re.M)
    n_rows = len(re.findall(r'^MS_(ITEM|ITEM_OOT|ALIAS_RG|SKIP_RG|SKIP_RI)\(', text, re.M))
    if n_rows != len(rows) + len(aliases) + len(skip_rg) + len(skip_ri):
        sys.exit('port_mm_rando: MsItems.def has %d rows but only %d parse' %
                 (n_rows, len(rows) + len(aliases) + len(skip_rg) + len(skip_ri)))
    return rows, aliases, skip_rg, skip_ri


def soh_enum(name):
    text = read(os.path.join(SOH_RANDO, 'randomizerEnums', name))
    return re.findall(r'RANDO_ENUM_ITEM\((\w+)', strip_comments(text))


def check_table(mm, rows, aliases, skip_rg, skip_ri, existing_rg):
    """The item table covers every item of both games exactly once. Returns a list of problems."""
    problems = []
    keys = collections.Counter(r['key'] for r in rows)
    problems += ['duplicate key %s' % k for k, n in keys.items() if n > 1]
    problems += ['key %s is not its RandomizerGet %s without RG_' % (r['key'], r['rg'])
                 for r in rows if r['rg'] != 'RG_' + r['key']]
    rg_uses = collections.Counter([r['rg'] for r in rows] + [a[0] for a in aliases] + skip_rg)
    problems += ['RandomizerGet %s appears %d times' % (k, n) for k, n in rg_uses.items() if n > 1]
    generated = {r['rg'] for r in rows if r['rg'] not in existing_rg}
    problems += ['RandomizerGet %s generated but not RG_MM_*' % g for g in generated if not g.startswith('RG_MM_')]
    for rg in existing_rg:
        if rg not in ('RG_MAX',) and rg not in rg_uses:
            problems.append('SoH RandomizerGet %s is not in MsItems.def' % rg)
    ri_native = [r['ri'] for r in rows if not r['proxy']]
    ri_uses = collections.Counter(ri_native + skip_ri)
    problems += ['RandoItemId %s appears %d times' % (k, n) for k, n in ri_uses.items() if n > 1]
    mm_items = [i for i in mm.item_ids if not i.startswith('RI_OOT_') and i != 'RI_MAX']
    for ri in mm_items:
        if ri not in ri_uses:
            problems.append('2Ship RandoItemId %s is not in MsItems.def' % ri)
    for ri in ri_uses:
        if ri not in mm_items:
            problems.append('MsItems.def names RandoItemId %s, which 2Ship does not have' % ri)
    for rg, key in aliases:
        if key not in keys:
            problems.append('alias %s -> unknown key %s' % (rg, key))
    for c, info in mm.checks.items():
        if info['item'] not in ri_uses:
            problems.append('check %s: vanilla item %s not in MsItems.def' % (c, info['item']))
    return problems


def ri_to_rg(rows, skip_ri):
    table = {r['ri']: r['rg'] for r in rows if not r['proxy']}
    for ri in skip_ri:
        table[ri] = 'RG_NONE'
    return table


def new_item_category(mm, r):
    """The SoH category of an item this tool generates: how 2Ship's randomizer shows it, else its kind's."""
    ritype = None if r['proxy'] else mm.item_types.get(r['ri'])
    return RITYPE_TO_CATEGORY[ritype] if ritype in RITYPE_TO_CATEGORY else KIND_TO_CATEGORY[r['kind']]


def soh_item_categories():
    """The category of each hand-written SoH item table row (item_list.cpp)."""
    cats = {}
    for part in re.split(r'(?=\bitemTable\[)', read(os.path.join(SOH_RANDO, 'item_list.cpp'))):
        m = re.match(r'itemTable\[(RG_\w+)\]\s*=\s*Item\(', part)
        c = re.search(r'\bITEM_CATEGORY_\w+', part) if m else None
        if c:
            cats[m.group(1)] = c.group(0)
    return cats


def check_camc(mm, rows, existing_rg):
    """Containers Match Contents across the worlds: every item looks the same in a Hyrule container as in a Termina
    one. A Termina item SoH names (RG_MM_*) must have 2Ship's look; a proxy RI_OOT_* takes SoH's look (the overrides
    written to ProxyItemTypes.inc). Returns (problems, overrides as [(key, RITYPE)])."""
    soh = soh_item_categories()
    for r in rows:
        if r['rg'] not in existing_rg:
            soh[r['rg']] = new_item_category(mm, r)
    by_kind = dict(re.findall(r'#define\s+MS_RITYPE_OF_(MS_KIND_\w+)\s+(RITYPE_\w+)', read(MS_ITEMS_H)))
    problems, overrides = [], []
    for r in rows:
        cat = soh.get(r['rg'])
        if cat not in CATEGORY_TO_RITYPE:
            problems.append('CAMC: no category for %s in SoH\'s item table' % r['rg'])
            continue
        # SoH's table gives masks Major; MergeShip_RandoMaskAdjustCategory draws every mask with the mask style.
        look = 'RITYPE_MASK' if r['kind'] == 'MS_KIND_MASK' else CATEGORY_TO_RITYPE[cat]
        if r['proxy']:
            if look != by_kind[r['kind']]:
                overrides.append((r['key'], look))
        elif r['rg'].startswith('RG_MM_') and look != mm.item_types.get(r['ri']):
            problems.append('CAMC: %s is %s in SoH\'s item table, but 2Ship shows %s as %s' %
                            (r['rg'], cat, r['ri'], mm.item_types.get(r['ri'])))
    return problems, overrides


def gen_files(mm, rows, skip_ri, existing_rg):
    out = {}
    ri_rg = ri_to_rg(rows, skip_ri)
    new_items = [r for r in rows if r['rg'] not in existing_rg]
    mm_checks = [c for c in mm.check_ids]

    # 2Ship: the proxies whose look differs from their kind's (check_camc).
    lines = ['// MergeShip2: ' + GEN_NOTE,
             '// From SoH\'s item table (Shipwright/soh/soh/Enhancements/randomizer/item_list.cpp) and MsItems.def:',
             '// the RandoItemType of each proxy RI_OOT_<key> whose SoH category (Containers Match Contents) is not its',
             '// kind\'s type (MsItems.h MS_KIND_TO_RITYPE), so that a Hyrule item looks the same in a Termina container',
             '// as in a Hyrule one. Included by Rando/StaticData/Items.cpp inside a table (no include guard).']
    lines += ['MS_PROXY_ITEM_TYPE(%s, %s)' % o for o in check_camc(mm, rows, existing_rg)[1]]
    out[MM_PROXY_TYPES] = '\n'.join(lines) + '\n'

    def inc_header():
        return '// MergeShip2: ' + GEN_NOTE + '\n// Included inside a RANDO_ENUM list (no include guard).\n'

    out[os.path.join(SOH_RANDO, 'randomizerEnums', 'RandomizerCheckTermina.inc')] = inc_header() + ''.join(
        'RANDO_ENUM_ITEM(RC_MM_%s)\n' % c[3:] for c in mm_checks)
