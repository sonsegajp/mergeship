"""Generates tools/oot3d/src/Oot3dFaceTable.inc: every eye and mouth texture array in the actor sources (the textures
an actor puts in a segment for each face state, in the actor's order: open, half, closed, ...), as resource paths.

The skin converter pairs entry i of an array with entry i of the 3DS model's eye / mouth texture palette (CMAB), so a
3DS face shows the state the N64 actor picked.
    py -3.13 tools/oot3d/gen_face_table.py
"""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Shipwright", "soh")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "Oot3dFaceTable.inc")

sym = {}
for dirpath, _dirs, files in os.walk(os.path.join(ROOT, "assets", "objects")):
    for f in files:
        if not f.endswith(".h"):
            continue
        for m in re.finditer(r'#define d(\w+) "__OTR__(objects/[^"]+)"', open(os.path.join(dirpath, f), encoding="utf-8",
                                                                             errors="replace").read()):
            sym[m.group(1)] = m.group(2)

arr = re.compile(r"(?:static\s+)?(?:const\s+)?(?:void|u64|u8|TexturePtr|Gfx)\s*\*?\s*(?:const\s+)?(\w+)\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}",
                 re.S)
entries = []
seen = set()
for dirpath, _dirs, files in os.walk(os.path.join(ROOT, "src", "overlays", "actors")):
    for f in sorted(files):
        if not f.endswith(".c"):
            continue
        src = open(os.path.join(dirpath, f), encoding="utf-8", errors="replace").read()
        for m in arr.finditer(src):
            name = m.group(1)
            items = [x.strip() for x in m.group(2).replace("\n", " ").split(",")]
            items = [re.sub(r"^\(\w+\s*\*?\)\s*", "", x) for x in items if x and x != "NULL"]
            paths = [sym.get(x) for x in items]
            if not paths or any(p is None for p in paths) or any("tex" not in p.split("/")[-1].lower() for p in paths):
                continue
            low = name.lower()
            leafs = " ".join(p.split("/")[-1].lower() for p in paths)
            if "mouth" in low or ("mouth" in leafs and "eye" not in low):
                kind = "m"
            elif "eye" in low or "eye" in leafs or "blink" in low:
                kind = "e"
            else:
                continue
            key = (kind, tuple(paths))
            if key in seen:
                continue
            seen.add(key)
            entries.append((kind, paths, f"{f}:{name}"))

with open(OUT, "w", encoding="utf-8", newline="\n") as o:
    o.write("// Generated by tools/oot3d/gen_face_table.py from the actor sources: eye ('e') and mouth ('m') texture\n"
            "// arrays in the actor's order (the index the actor picks), as resource paths.\n")
    for kind, paths, where in entries:
        o.write(f"{{ '{kind}', {{ " + ", ".join(f'"{p}"' for p in paths) + f" }} }}, // {where}\n")
print(f"{len(sym)} texture symbols, {len(entries)} face arrays -> {OUT}")
