#!/usr/bin/env python3
"""MergeShip2 -- port 2 Ship 2 Harkinian's randomizer static data and logic into Ship of Harkinian's randomizer.

Unified randomizer, milestones M1 (static data) and M4 (logic) (Shipwright/mergeship2/docs/UNIFIED_RANDO_DESIGN.md).
Re-runnable: 2Ship upstream moves, so every output is regenerated from 2Ship's sources each run. It never edits
hand-written files.

Reads (2ship2harkinian/mm/2s2h/Rando):
    Types.h                 RandoCheckId, RandoCheckType, RandoItemId, RandoRegionId, RandoOptionId, RandoEvent, option
                            enums
    StaticData/Checks.cpp   RC(...) rows: check type, scene, vanilla item
    StaticData/Options.cpp  RO(...) rows: option defaults
    Logic/Logic.h           the 45 TimeSlices
    Logic/Regions/*.cpp     the world graph: each region's checks, exits, connections, events, one-way entrances and
                            time-stay restrictions, with their conditions (and the files' local helpers)
    Logic/Logic.cpp         the pseudo-root RR_MAX (starting items, save warp, owl warps), which becomes RR_MM_ROOT
and include/mergeship/MsItems.def (the canonical item table: the RandoItemId -> RandomizerGet mapping), and
soh/MergeShip/MergeShipTerminaLogic.h (hand-written: the enumerators the translated conditions may use).

Writes (Shipwright/soh/soh/Enhancements/randomizer unless noted):
    randomizerEnums/RandomizerCheckTermina.inc      RC_MM_<check>     (appended before RC_MAX)
    randomizerEnums/RandomizerGetTermina.inc        RG_MM_<item> the table names that SoH does not define yet
    randomizerEnums/RandomizerRegionTermina.inc     RR_MM_<region>, RR_MM_ROOT
    randomizerEnums/RandomizerSettingKeyTermina.inc RSK_MM_<option>
    randomizerEnums/LogicValTermina.inc             LOGIC_MM_<event> (2Ship's RandoEvents and the unified goals)
    location_list_termina.cpp                       StaticData::InitTerminaLocationTable (world-tagged locations)
    item_list_termina.cpp                           StaticData::InitTerminaItemTable (the new RG_MM_* items)
    settings_termina.inc                            the RSK_MM_* options, included by Settings::CreateOptions
    location_access/termina/*.cpp                   2Ship's Logic/Regions translated: one file per 2Ship file, and
                                                    root.cpp (RegionTable_Init_Termina: the pseudo-root, the door)
    ../../MergeShip/MergeShipTerminaData.cpp        per-check 2Ship data, option table, region table (see
                                                    MergeShipTerminaRando.h)
    ../../MergeShip/MergeShipTerminaLogicGen.h      MMTimeSlice (MMT_*), MMOption (MMO_*), MM_RO_* option values
    2ship2harkinian/mm/2s2h/Rando/MergeShip/ProxyItemTypes.inc
                                                    the proxies' RandoItemType where SoH's category is not their
                                                    kind's (Containers Match Contents, check_camc)

Condition translation (2Ship macro -> SoH, MergeShipTerminaLogic.h implements the calls):
    HAS_ITEM(ITEM_X) -> mm->Has(MMI_X)       CAN_BE_DEKU -> mm->CanBeDeku()    RANDO_EVENTS[RE_X] -> logic->Get(LOGIC_MM_X)
    CanKillEnemy(ACTOR_X) -> mm->CanKillEnemy(MMA_X)    BETWEEN(TIME_A, TIME_B) -> mm->Between(MMT_A, MMT_B)
    RANDO_SAVE_OPTIONS[RO_X] -> mm->Option(MMO_X)       ...  (see TRANSLATE_* below)
An identifier the translator does not know is a problem (--check fails): 2Ship's logic grew, port it.

Usage:
    python tools/port_mm_rando.py            generate
    python tools/port_mm_rando.py --check    only verify (item table coverage, logic translation, generated files up
                                             to date); exit 1 on any problem
"""
