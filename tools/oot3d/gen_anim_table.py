"""Generates tools/oot3d/src/Oot3dAnimTable.inc: for each vanilla skeleton, the animations the game plays on it.

N64 actors often animate a skeleton with animations from other objects (Hylians and Kokiri use object_os_anime,
Link uses gameplay_keep's player animations), so an object's own animations are not the full set. SoH's actor
sources name both: every skeleton and animation symbol an actor file references is an OTR resource of the same name.
Skeletons referenced by one actor file get all animations referenced by that file (the converter then keeps the
ones whose joint count fits the skeleton).

Usage: python tools/oot3d/gen_anim_table.py <oot.o2r>
"""

import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "Shipwright", "soh", "src")
OUT = os.path.join(ROOT, "tools", "oot3d", "src", "Oot3dAnimTable.inc")
OUT_DL = os.path.join(ROOT, "tools", "oot3d", "src", "Oot3dDlTable.inc")
OUT_XLU = os.path.join(ROOT, "tools", "oot3d", "src", "Oot3dXluLists.inc")

SKEL_RX = re.compile(r"\b((?:g\w*Skel|object_\w+_Skel_\w+))\b")
ANIM_RX = re.compile(r"\b((?:g\w*Anim\w*|object_\w+_Anim_\w+))\b")
# A list drawn into the translucent display list: gSPDisplayList(POLY_XLU_DISP++, X) or Gfx_DrawDListXlu(play, X), X a
# list symbol or an array of them (static Gfx* D_...[] = { ... }).
XLU_RX = re.compile(r"(?:POLY_XLU_DISP\+\+|Gfx_DrawDListXlu\(\s*\w+)\s*,\s*(\w+)")
ARRAY_RX = re.compile(r"static\s+Gfx\s*\*\s*(\w+)\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}")
DL_RX = re.compile(r"\b((?:g\w*DL\w*|object_\w+_DL_\w+))\b")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    names = zipfile.ZipFile(sys.argv[1]).namelist()
    by_symbol = {}
    for n in names:
        if n.startswith("objects/"):
            by_symbol.setdefault(n.rsplit("/", 1)[1], []).append(n)

    table = {}
    dl_table = {}
    xlu = set()
    files = 0
    for root, _dirs, fnames in os.walk(SRC):
        for f in fnames:
            if not f.endswith(".c"):
                continue
            text = open(os.path.join(root, f), encoding="utf-8", errors="replace").read()
            arrays = {m.group(1): re.findall(r"\w+", m.group(2)) for m in ARRAY_RX.finditer(text)}
            for name in XLU_RX.findall(text):
                for sym in arrays.get(name, [name]):
                    xlu.update(by_symbol.get(sym, []))
            skels = set()
            for s in SKEL_RX.findall(text):
                skels.update(by_symbol.get(s, []))
            if not skels:
                continue
            anims = set()
            for a in ANIM_RX.findall(text):
                anims.update(by_symbol.get(a, []))
            dls = set()
            for d in DL_RX.findall(text):
                dls.update(by_symbol.get(d, []))
            files += 1
            for s in skels:
                table.setdefault(s, set()).update(anims)
                dl_table.setdefault(s, set()).update(dls)

    lines = [
        "// Generated by tools/oot3d/gen_anim_table.py from SoH's actor sources: the animations the game plays on each",
        "// vanilla skeleton (including other objects' animations). Do not edit.",
    ]
    for skel in sorted(table):
        anims = sorted(table[skel])
        body = ", ".join(f'"{a}"' for a in anims)
        lines.append(f'{{ "{skel}", {{ {body} }} }},')
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(table)} skeletons from {files} source files -> {OUT}")
    lines = [
        "// Generated by tools/oot3d/gen_anim_table.py from SoH's actor sources: the display lists the actors that use",
        "// each vanilla skeleton reference (limb overrides such as En_Hy's heads, held props). Do not edit.",
    ]
    for skel in sorted(dl_table):
        if not dl_table[skel]:
            continue
        body = ", ".join(f'"{d}"' for d in sorted(dl_table[skel]))
        lines.append(f'{{ "{skel}", {{ {body} }} }},')
    open(OUT_DL, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(lines) - 2} skeletons with referenced display lists -> {OUT_DL}")
    lines = [
        "// Generated by tools/oot3d/gen_anim_table.py from SoH's actor sources: display lists actors draw into the",
        "// translucent display list (POLY_XLU). Do not edit.",
    ]
    lines += [f'"{d}",' for d in sorted(xlu)]
    open(OUT_XLU, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(xlu)} translucent lists -> {OUT_XLU}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
