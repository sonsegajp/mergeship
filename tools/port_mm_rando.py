def tokenize(text):
    """Tokens without whitespace and comments (preprocessor lines must be removed first)."""
    return [t for t in TOKEN_RE.findall(text) if not t.isspace() and not t.startswith('//') and not t.startswith('/*')]


def match_close(ts, i):
    """Index of the token closing the bracket ts[i]."""
    depth = 0
    for j in range(i, len(ts)):
        if ts[j] in ('(', '[', '{'):
            depth += 1
        elif ts[j] in (')', ']', '}'):
            depth -= 1
            if depth == 0:
                return j
    raise ValueError('unbalanced bracket at %s' % ' '.join(ts[i:i + 12]))


def split_top(ts, sep=','):
    """Split tokens at top-level separators; a trailing empty part is dropped."""
    parts, cur, depth = [], [], 0
    for t in ts:
        if t in ('(', '[', '{'):
            depth += 1
        elif t in (')', ']', '}'):
            depth -= 1
        if t == sep and depth == 0:
            parts.append(cur)
            cur = []
        else:
            cur.append(t)
    if cur:
        parts.append(cur)
    return parts


def join_tokens(ts):
    """C++ text of translated tokens (each already an atom: an operator, a bracket or a translated call)."""
    out = ''
    prev = ''
    for t in ts:
        if not out:
            out = t
        elif t in (')', ']', ',', ';'):
            out += t
        elif prev in ('(', '[', '!'):
            out += t
        elif t == '(' and IDENT_RE.match(prev) and prev not in KEYWORDS:
            out += t
        else:
            out += ' ' + t
        prev = t
    return out


class Translator:
    """Rewrites 2Ship condition tokens into SoH C++ over MergeShipTerminaLogic.h; unknown names become problems."""

    def __init__(self, known, time_slices, events, options, option_values, checks, local_defines, local_functions):
        self.known = known  # enumerator prefix (MMI, MMA, ...) -> names MergeShipTerminaLogic.h declares
        self.time_slices = set(time_slices)
        self.events = set(events)
        self.options = set(options)
        self.option_values = set(option_values)
        self.checks = set(checks)
        self.local_defines = local_defines
        self.local_functions = local_functions
        self.counted = {}  # event -> how many EVENT()s set it, for events the logic counts (RANDO_EVENTS[RE_X] >= n)
        self.problems = []
        self.where = ''

    def problem(self, msg):
        self.problems.append('%s: %s' % (self.where, msg))
        return 'false'

    def enum(self, prefix, name):
        if name not in self.known.get(prefix, set()):
            return self.problem('%s is not in MergeShipTerminaLogic.h (add it, and what it means)' % name)
        return name

    def arg1(self, name, args, strip, prefix):
        if len(args) != 1 or len(args[0]) != 1 or not args[0][0].startswith(strip):
            return self.problem('unexpected arguments to %s: %s' % (name, args))
        return self.enum(prefix, prefix + '_' + args[0][0][len(strip):])

    def time(self, tok):
        if not tok.startswith('TIME_') or tok[5:] not in self.time_slices:
            return self.problem('unknown time slice %s' % tok)
        return 'MMT_' + tok[5:]

    def event(self, tok):
        if tok not in self.events:
            return self.problem('unknown event %s' % tok)
        return 'LOGIC_MM_' + tok[3:]

    def call(self, name, a):
        if name == 'HAS_ITEM':
            return 'mm->Has(%s)' % self.arg1(name, a, 'ITEM_', 'MMI')
        if name == 'HAS_BOTTLE_ITEM':
            return 'mm->HasBottleItem(%s)' % self.arg1(name, a, 'ITEM_', 'MMI')
        if name == 'CAN_PLAY_SONG':
            return 'mm->CanPlaySong(%s)' % self.arg1(name, a, '', 'MMSONG')
        if name == 'CAN_USE_MAGIC_ARROW':
            return 'mm->CanUseMagicArrow(%s)' % self.arg1(name, [['ARROW_' + a[0][0]]] if a and a[0] else a, '',
                                                          'MMI')
        if name == 'CAN_USE_ABILITY':
            if a != [['SWIM']]:
                return self.problem('CAN_USE_ABILITY %s (only SWIM is ported)' % a)
            return 'mm->CanSwim()'
        if name == 'CAN_ACCESS':
            return 'logic->Get(%s)' % self.event('RE_ACCESS_' + a[0][0])
        if name == 'CAN_AFFORD':
            if len(a) != 1 or a[0][0] not in self.checks:
                return self.problem('CAN_AFFORD of unknown check %s' % a)
            return 'mm->CanAfford(RC_MM_%s)' % a[0][0][3:]
        if name == 'CAN_OWL_WARP':
            return 'mm->CanOwlWarp(%s)' % self.arg1(name, a, 'OWL_WARP_', 'MMOWL')
        if name == 'CHECK_QUEST_ITEM':
            return 'mm->Quest(%s)' % self.arg1(name, a, 'QUEST_', 'MMQ')
        if name == 'CHECK_DUNGEON_ITEM':
            if len(a) != 2 or a[0] != ['DUNGEON_BOSS_KEY']:
                return self.problem('CHECK_DUNGEON_ITEM %s (only the boss key is ported)' % a)
            return 'mm->BossKey(%s)' % self.arg1(name, a[1:], 'DUNGEON_SCENE_INDEX_', 'MMD')
        if name == 'CHECK_WEEKEVENTREG':
            return 'mm->WeekEvent(%s)' % self.arg1(name, a, 'WEEKEVENTREG_', 'MMW')
        if name == 'CHECK_MAX_HP':
            return 'mm->CheckMaxHp(%s)' % self.expr(a[0])
        if name == 'KEY_COUNT':
            return 'mm->KeyCount(%s)' % self.arg1(name, a, '', 'MMD')
        if name == 'HAS_ENOUGH_STRAY_FAIRIES':
            return 'mm->HasEnoughStrayFairies(%s)' % self.arg1(name, a, 'DUNGEON_SCENE_INDEX_', 'MMD')
        if name == 'HAS_ENOUGH_SKULLTULA_TOKENS':
            if len(a) != 1 or len(a[0]) != 1 or a[0][0] not in SPIDER_HOUSES:
                return self.problem('HAS_ENOUGH_SKULLTULA_TOKENS %s' % a)
            return 'mm->HasEnoughSkulltulaTokens(%s)' % SPIDER_HOUSES[a[0][0]]
        if name == 'GET_CUR_EQUIP_VALUE':
            if a != [['EQUIP_TYPE_SHIELD']]:
                return self.problem('GET_CUR_EQUIP_VALUE %s (only the shield is ported)' % a)
            return 'mm->ShieldLevel()'
        if name in ('GET_CUR_UPG_VALUE', 'CUR_UPG_VALUE'):
            if a != [['UPG_WALLET']]:
                return self.problem('%s %s (only the wallet is ported)' % (name, a))
            return 'mm->WalletLevel()'
        if name == 'Flags_GetRandoInf':
            return 'mm->RandoInf(%s)' % self.arg1(name, a, 'RANDO_INF_', 'MMRI')
        if name == 'CanKillEnemy':
            return 'mm->CanKillEnemy(%s)' % self.arg1(name, a, 'ACTOR_', 'MMA')
        if name == 'CanAccessDungeon':
            return 'mm->CanAccessDungeon(%s)' % self.arg1(name, a, 'DUNGEON_SCENE_INDEX_', 'MMD')
        if name == 'canPlaySong':
            return 'mm->CanPlayOcarinaSong(%s)' % self.arg1(name, a, 'OCARINA_SONG_', 'MMOS')
        if name == 'BETWEEN':
            if len(a) != 2:
                return self.problem('BETWEEN %s' % a)
            return 'mm->Between(%s, %s)' % (self.time(a[0][0]), self.time(a[1][0]))
        if name in ('BEFORE', 'AFTER', 'AT'):
            if len(a) != 1:
                return self.problem('%s %s' % (name, a))
            return 'mm->%s(%s)' % ({'BEFORE': 'Before', 'AFTER': 'After', 'AT': 'At'}[name], self.time(a[0][0]))
        if name in TRANSLATE_NOARG:
            if a:
                return self.problem('%s takes no arguments' % name)
            return 'mm->%s()' % TRANSLATE_NOARG[name]
        if name in CLOCK_MACROS:
            return 'mm->OwnsHalfDayForMode(%d)' % CLOCK_MACROS[name]
        if name in self.local_functions:
            return 'Local_%s(%s)' % (name, ', '.join(self.expr(x) for x in a))
        return self.problem('unknown function-like %s' % name)

    def index(self, name, inner):
        if name == 'RANDO_EVENTS' and len(inner) == 1 and inner[0] in self.counted:
            # 2Ship counts an event once per EVENT() that fired: each has its own LogicVal here, summed.
            base = self.event(inner[0])
            return '(%s)' % ' + '.join('(int)logic->Get(%s_%d)' % (base, n + 1) for n in range(self.counted[inner[0]]))
        if name == 'RANDO_EVENTS' and len(inner) == 1:
            return 'logic->Get(%s)' % self.event(inner[0])
        if name == 'RANDO_SAVE_OPTIONS' and len(inner) == 1 and inner[0] in self.options:
            return 'mm->Option(MMO_%s)' % inner[0][3:]
        return self.problem('unknown subscript %s[%s]' % (name, ' '.join(inner)))

    def ident(self, name):
        if name in TRANSLATE_OBJECTS:
            return TRANSLATE_OBJECTS[name]
        if name in KEYWORDS:
            return name
        if name in self.option_values:
            return 'MM_' + name
        if name in self.local_defines:
            return 'Local_%s()' % name
        return self.problem('unknown identifier %s' % name)

    def expr(self, ts):
        out = []
        i = 0
        while i < len(ts):
            t = ts[i]
            nxt = ts[i + 1] if i + 1 < len(ts) else None
            if IDENT_RE.match(t) and t not in KEYWORDS:
                if nxt == '(':
                    j = match_close(ts, i + 1)
                    out.append(self.call(t, split_top(ts[i + 2:j])))
                    i = j + 1
                    continue
                if nxt == '[':
                    j = match_close(ts, i + 1)
                    out.append(self.index(t, ts[i + 2:j]))
                    i = j + 1
                    continue
                out.append(self.ident(t))
            else:
                out.append(t)
            i += 1
        return join_tokens(out)

    def body(self, ts):
        """A local helper function's statements (if / return / blocks), one per line."""
        lines, depth, cur = [], 1, []

        def flush():
            if cur:
                lines.append('    ' * depth + self.expr(cur))
                del cur[:]

        i = 0
        while i < len(ts):
            t = ts[i]
            if t == 'if' and i + 1 < len(ts) and ts[i + 1] == '(':
                j = match_close(ts, i + 1)
                flush()
                cur.extend(ts[i:j + 1])
                i = j + 1
                continue
            if t == '{':
                lines.append('    ' * depth + self.expr(cur) + ' {')
                del cur[:]
                depth += 1
            elif t == '}':
                flush()
                depth -= 1
                lines.append('    ' * depth + '}')
            elif t == ';':
                cur.append(';')
                flush()
            else:
                cur.append(t)
            i += 1
        flush()
        return lines


def parse_macro_call(ts):
    """NAME ( args ) -> (NAME, [argument token lists])."""
    if len(ts) < 3 or ts[1] != '(' or ts[-1] != ')':
        raise ValueError('not a macro call: %s' % ' '.join(ts[:16]))
    return ts[0], split_top(ts[2:-1])


def entrance_key(ts):
    """ENTRANCE(SCENE, n) -> 'SCENE,n'; ONE_WAY_EXIT -> None."""
    if ts == ['ONE_WAY_EXIT']:
        return None
    name, args = parse_macro_call(ts)
    if name != 'ENTRANCE' or len(args) != 2:
        raise ValueError('not an entrance: %s' % ' '.join(ts))
    return '%s,%s' % (''.join(args[0]), ''.join(args[1]))


def parse_region_body(ts):
    """The designated initializers of a RandoRegion: field -> [(macro, args)] for lists, tokens otherwise."""
    fields = {}
    i = 0
    while i < len(ts):
        if ts[i] == ',':
            i += 1
            continue
        if ts[i] != '.' or i + 2 >= len(ts) or ts[i + 2] != '=':
            raise ValueError('unexpected region field syntax: %s' % ' '.join(ts[i:i + 10]))
        field = ts[i + 1]
        j = i + 3
        if ts[j] == '{':
            end = match_close(ts, j)
            fields[field] = [parse_macro_call(e) for e in split_top(ts[j + 1:end])]
            i = end + 1
        else:
            k = j
            while k < len(ts) and ts[k] != ',':
                k += 1
            fields[field] = ts[j:k]
            i = k
    return fields


def parse_region_source(path):
    """A 2Ship region file: its local #defines and inline bool functions, and its regions."""
    text = read(path)
    text = re.sub(r'\\\r?\n', ' ', text)  # join macro continuations
    defines = collections.OrderedDict()
    for m in re.finditer(r'^[ \t]*#define[ \t]+(\w+)[ \t]+(.*)$', text, re.M):
        defines[m.group(1)] = tokenize(m.group(2))
    text = '\n'.join(l for l in text.splitlines() if not l.lstrip().startswith('#'))
    ts = tokenize(text)
    functions = collections.OrderedDict()
    regions = []
    i = 0
    while i < len(ts):
        if ts[i:i + 2] == ['inline', 'bool'] and ts[i + 3:i + 6] == ['(', ')', '{']:
            end = match_close(ts, i + 5)
            functions[ts[i + 2]] = ts[i + 6:end]
            i = end + 1
            continue
        if ts[i:i + 2] == ['Regions', '['] and ts[i + 3:i + 7] == [']', '=', 'RandoRegion', '{']:
            end = match_close(ts, i + 6)
            regions.append((ts[i + 2], parse_region_body(ts[i + 7:end])))
            i = end + 1
            continue
        i += 1
    return defines, functions, regions


def parse_time_slices():
    text = strip_comments(read(os.path.join(MM_LOGIC, 'Logic.h')))
    m = re.search(r'enum\s+TimeSlice\s*\{(.*?)\}', text, re.S)
    if not m:
        sys.exit('port_mm_rando: TimeSlice not found in Logic.h')
    return [e.split('=')[0].strip()[5:] for e in m.group(1).split(',') if e.strip()]  # without TIME_


def parse_logic_header():
    """The enumerators MergeShipTerminaLogic.h declares, by prefix (MMI, MMA, MMSONG, ...)."""
    text = strip_comments(read(TERMINA_LOGIC_H))
    known = collections.defaultdict(set)
    for m in re.finditer(r'enum\s+\w+\s*\{(.*?)\}', text, re.S):
        for e in m.group(1).split(','):
            name = e.split('=')[0].strip()
            if name:
                known[name.split('_')[0]].add(name)
    return known


class MMRegion:
    def __init__(self, rr, source):
        self.rr = rr
        self.source = source
        self.scene = 'SCENE_MAX'
        self.checks = []       # (rc, condition tokens)
        self.exits = []        # (to entrance key, from entrance key or None, condition tokens)
        self.connections = []  # (rr, condition tokens)
        self.events = []       # (re, condition tokens)
        self.one_way = []      # entrance keys
        self.stays = []        # (time slice token, condition tokens)


REGION_FIELDS = {'name', 'sceneId', 'checks', 'exits', 'connections', 'events', 'oneWayEntrances',
                 'timeStayRestrictions'}


def parse_logic(mm):
    lg = Data()
    types = read(os.path.join(MM, 'Types.h'))
    lg.events = [e for e in enum_body(types, 'RandoEvent') if e != 'RE_MAX']
    lg.time_slices = parse_time_slices()
    lg.known = parse_logic_header()
    lg.regions = collections.OrderedDict()
    lg.locals = {}  # source -> (defines, functions)
    on_disk = sorted(f[:-4] for f in os.listdir(os.path.join(MM_LOGIC, 'Regions')) if f.endswith('.cpp'))
    lg.problems = ['2Ship region file %s.cpp is not in REGION_FILES' % f for f in on_disk if f not in REGION_FILES]
    lg.problems += ['REGION_FILES names %s, which 2Ship does not have' % f for f in REGION_FILES if f not in on_disk]
    sources = [(f, os.path.join(MM_LOGIC, 'Regions', f + '.cpp')) for f in REGION_FILES if f in on_disk]
    sources.append(('Root', os.path.join(MM_LOGIC, 'Logic.cpp')))
    for source, path in sources:
        defines, functions, regions = parse_region_source(path)
        lg.locals[source] = (defines, functions)
        for rr, fields in regions:
            if rr in lg.regions:
                lg.problems.append('region %s defined twice' % rr)
            r = MMRegion(rr, source)
            unknown = set(fields) - REGION_FIELDS
            if unknown:
                lg.problems.append('%s: unported region fields %s' % (rr, sorted(unknown)))
            if 'sceneId' in fields:
                r.scene = fields['sceneId'][0]
            for name, args in fields.get('checks', []):
                r.checks.append((args[0][0], args[1]))
            for name, args in fields.get('exits', []):
                r.exits.append((entrance_key(args[0]), entrance_key(args[1]), args[2]))
            for name, args in fields.get('connections', []):
                r.connections.append((args[0][0], args[1]))
            for name, args in fields.get('events', []):
                r.events.append((args[0][0], args[1]))
            for name, args in fields.get('oneWayEntrances', []):
                r.one_way.append('%s,%s' % (''.join(args[0]), ''.join(args[1])))
            for name, args in fields.get('timeStayRestrictions', []):
                r.stays.append((args[0][0], args[1]))
            lg.regions[rr] = r
    # Entrances -> regions, as 2Ship's GetRegionIdFromEntrance builds it (its std::map iterates in RandoRegionId
    # order, a later region overwriting an earlier one).
    order = {rr: i for i, rr in enumerate(mm.region_ids + ['RR_MAX'])}
    lg.entrance_region = {}
    for rr in sorted(lg.regions, key=lambda r: order.get(r, 1 << 20)):
        r = lg.regions[rr]
        for to, frm, cond in r.exits:
            if frm is not None:
                lg.entrance_region[frm] = rr
        for e in r.one_way:
            lg.entrance_region[e] = rr
    return lg


def soh_rr(rr):
    return 'RR_MM_ROOT' if rr == 'RR_MAX' else 'RR_MM_' + rr[3:]


def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()


def gen_logic_files(mm, lg):
    """location_access/termina/*.cpp, LogicValTermina.inc, MergeShipTerminaLogicGen.h -> (files, stats, problems)."""
    out = collections.OrderedDict()
    problems = list(lg.problems)
    # Events 2Ship's logic counts (RANDO_EVENTS[RE_X] compared with a number): one LogicVal per EVENT() setting it.
    counted = collections.OrderedDict()
    for r in lg.regions.values():
        for e, cond in r.events:
            counted.setdefault(e, 0)
            counted[e] += 1
    compared = set()
    everything = [c for r in lg.regions.values() for c in
                  [x[1] for x in r.checks] + [x[2] for x in r.exits] + [x[1] for x in r.connections] +
                  [x[1] for x in r.events] + [x[1] for x in r.stays]]
    everything += [b for d, f in lg.locals.values() for b in list(d.values()) + list(f.values())]
    for ts in everything:
        for i in range(len(ts) - 4):
            if ts[i:i + 2] == ['RANDO_EVENTS', '['] and ts[i + 3] == ']' and ts[i + 4] in ('>=', '>', '==', '<=', '<',
                                                                                          '!='):
                compared.add(ts[i + 2])
    counted = collections.OrderedDict((e, n) for e, n in counted.items() if e in compared)
    problems += ['event %s is counted but never set' % e for e in compared if e not in counted]
    logicvals = ['LOGIC_MM_' + e[3:] for e in lg.events] + list(GOAL_EVENTS.values())
    logicvals += ['LOGIC_MM_%s_%d' % (e[3:], n + 1) for e, total in counted.items() for n in range(total)]
    occurrence = collections.Counter()
    existing = set(soh_enum('LogicVal.h'))
    ours = os.path.join(SOH_RANDO, 'randomizerEnums', 'LogicValTermina.inc')
    if os.path.exists(ours):
        existing -= set(re.findall(r'RANDO_ENUM_ITEM\((\w+)', read(ours)))
    problems += ['LogicVal %s already exists in SoH' % v for v in logicvals if v in existing]
    if MAJORA_EVENT not in existing:
        problems.append('LogicVal %s (the unified goal\'s, LogicVal.h) is missing' % MAJORA_EVENT)
    problems += ['goal check %s is in no region' % rc for rc in GOAL_EVENTS
                 if not any(rc == c for r in lg.regions.values() for c, _ in r.checks)]
    if MAJORA_REGION not in lg.regions:
        problems.append('Majora\'s region %s is gone' % MAJORA_REGION)

    option_values = set()
    for name in set(ENUM_OPTIONS.values()):
        option_values |= set(mm.option_enums[name])

    stats = collections.Counter()
    in_region = set()
    region_lines = collections.OrderedDict()
    helper_lines = collections.OrderedDict()
    for source in REGION_FILES + ['Root']:
        if source not in lg.locals:
            continue
        defines, functions = lg.locals[source]
        t = Translator(lg.known, lg.time_slices, lg.events, list(mm.options), option_values, mm.check_ids,
                       set(defines), set(functions))
        t.counted = counted
        helpers = []
        if defines or functions:
            # Declared first: a helper may use one defined after it.
            helpers += ['static bool Local_%s();' % n for n in list(defines) + list(functions)] + ['']
        for name, body in defines.items():
            t.where = '%s #define %s' % (source, name)
            helpers += ['static bool Local_%s() {' % name, '    return %s;' % t.expr(body), '}', '']
        for name, body in functions.items():
            t.where = '%s %s()' % (source, name)
            helpers += ['static bool Local_%s() {' % name] + t.body(body) + ['}', '']
        helper_lines[source] = helpers
        lines = []
        for rr, r in lg.regions.items():
            if r.source != source:
                continue
            stats['regions'] += 1
            t.where = rr
            events = []
            for e, cond in r.events:
                events.append('EVENT_ACCESS(%s, %s)' % (t.event(e), t.expr(cond)))
                stats['events'] += 1
                if e in counted:
                    occurrence[e] += 1
                    events.append('EVENT_ACCESS(%s_%d, %s)' % (t.event(e), occurrence[e], t.expr(cond)))
                    stats['counted event occurrences'] += 1
            for rc, cond in r.checks:
                if rc in GOAL_EVENTS:
                    events.append('EVENT_ACCESS(%s, %s)' % (GOAL_EVENTS[rc], t.expr(cond)))
                    stats['goal events'] += 1
            if rr == MAJORA_REGION:
                events.append('EVENT_ACCESS(%s, mm->CanDefeatMajora())' % MAJORA_EVENT)
                stats['goal events'] += 1
            locations = []
            for rc, cond in r.checks:
                if rc not in mm.checks:
                    problems.append('%s lists unknown check %s' % (rr, rc))
                    continue
                locations.append('LOCATION(RC_MM_%s, %s)' % (rc[3:], t.expr(cond)))
                in_region.add(rc)
                stats['location entries'] += 1
            # 2Ship's exits go to entrance ids, resolved as its GetRegionIdFromEntrance does; with its connections,
            # one SoH exit per target region (two ways into the same region become one condition).
            targets = collections.OrderedDict()
            for to, frm, cond in r.exits:
                target = lg.entrance_region.get(to)
                if target is None:
                    # No region returns through this entrance: 2Ship's GetRegionIdFromEntrance gives RR_MAX, the
                    # pseudo-root (e.g. Goht's warp to the spring-time Mountain Village).
                    target = 'RR_MAX'
                    stats['exits to the root (no region at their entrance)'] += 1
                targets.setdefault(target, []).append(t.expr(cond))
                stats['exits'] += 1
            for target, cond in r.connections:
                if target not in lg.regions:
                    problems.append('%s: connection to undefined region %s' % (rr, target))
                    continue
                targets.setdefault(target, []).append(t.expr(cond))
                stats['connections'] += 1
            exits = []
            for target, conds in targets.items():
                if target == rr:
                    continue
                if 'true' in conds:
                    cond = 'true'
                elif len(conds) == 1:
                    cond = conds[0]
                else:
                    cond = ' || '.join('(%s)' % c for c in conds)
                exits.append('ENTRANCE(%s, %s)' % (soh_rr(target), cond))
            name = 'MM ' + ('Root' if rr == 'RR_MAX' else readable(rr, 'RR_'))
            lines.append('// 2Ship %s (%s)' % (rr, r.scene))
            lines.append('static void Init_%s() {' % soh_rr(rr))
            lines.append('    areaTable[%s] = Region(%s, SCENE_ID_MAX, TIME_DOESNT_PASS, {RA_NONE}, {' %
                         (soh_rr(rr), cstr(name)))
            if events:
                lines += ['        //Events'] + ['        %s,' % e for e in events]
            lines.append('    }, {')
            if locations:
                lines += ['        //Locations'] + ['        %s,' % l for l in locations]
            lines.append('    }, {')
            if exits:
                lines += ['        //Exits'] + ['        %s,' % e for e in exits]
            lines.append('    });')
            lines.append('    areaTable[%s].world = RW_TERMINA;' % soh_rr(rr))
            if r.stays:
                lines.append('    MsTermina::SetStays(%s, {' % soh_rr(rr))
                for s, c in r.stays:
                    lines.append('        { %s, [] { return %s; } },' % (t.time(s), t.expr(c)))
                lines.append('    });')
                stats['stays'] += len(r.stays)
            lines += ['}', '']
        region_lines[source] = lines
        problems += t.problems
    problems += ['check %s is in no region' % c for c in mm.check_ids if c not in in_region]
    stats['checks in a region'] = len(in_region)

    head = ['// MergeShip2: ' + GEN_NOTE, '',
            '#include "soh/Enhancements/randomizer/location_access.h"',
            '#include "soh/Enhancements/randomizer/entrance.h"',
            '#include "soh/MergeShip/MergeShipTerminaLogic.h"', '',
            'using namespace Rando;', 'using namespace MsTermina;', '']

    init_calls = []
    for source in REGION_FILES:
        if source not in region_lines:
            continue
        fname = 'RegionTable_Init_Termina_' + source
        fns = [l.split()[2].split('(')[0] for l in region_lines[source] if l.startswith('static void Init_')]
        body = list(head)
        body[1] = ('// Termina: 2Ship\'s Logic/Regions/%s.cpp in SoH\'s logic framework (unified randomizer M4, '
                   'MergeShipTerminaLogic.h).' % source)
        body += ['// clang-format off'] + helper_lines[source] + region_lines[source]
        body += ['void %s() {' % fname] + ['    %s();' % f for f in fns] + ['}', '// clang-format on', '']
        out[os.path.join(SOH_TERMINA, snake(source) + '.cpp')] = '\n'.join(body)
        init_calls.append(fname)

    body = list(head)
    body[1] = ('// Termina\'s root (unified randomizer M4): 2Ship\'s pseudo-root RR_MAX (Logic.cpp) as RR_MM_ROOT, the door '
               'from Hyrule, and\n// every translated region file (MergeShipTerminaLogic.h).')
    body += ['// clang-format off'] + ['void %s();' % f for f in init_calls] + ['']
    body += helper_lines.get('Root', []) + region_lines['Root']
    body += ['void RegionTable_Init_Termina() {', '    MsTermina::BeginRegionTable();']
    body += ['    %s();' % f for f in init_calls]
    body += ['    Init_RR_MM_ROOT();',
             '    // The door (lost_woods.cpp RR_LW_TERMINA_DOOR) lands in the Clock Tower; 2Ship\'s pseudo-root (save warp,',
             '    // owl warps) is one step away whenever Termina is.',
             '    areaTable[RR_MM_CLOCK_TOWER_INTERIOR].exits.push_back(ENTRANCE(RR_LW_TERMINA_DOOR, true));',
             '    areaTable[RR_MM_CLOCK_TOWER_INTERIOR].exits.push_back(ENTRANCE(RR_MM_ROOT, true));',
             '}', '// clang-format on', '']
    out[os.path.join(SOH_TERMINA, 'root.cpp')] = '\n'.join(body)

    out[ours] = ('// MergeShip2: ' + GEN_NOTE + '\n'
                 '// Included inside the LogicVal RANDO_ENUM list (no include guard): 2Ship\'s RandoEvents as SoH events,\n'
                 '// then the unified goals\' MM bosses defeated (Majora\'s is LogicVal.h\'s LOGIC_MM_MAJORA_DEFEATED).\n' +
                 ''.join('RANDO_ENUM_ITEM(%s)\n' % v for v in logicvals))

    lines = ['#pragma once', '// MergeShip2: ' + GEN_NOTE,
             '// 2Ship\'s time slices and options for Termina\'s logic (MergeShipTerminaLogic.h).', '',
             'namespace MsTermina {', '', '// Logic.h TimeSlice: 45 points of the three days.', 'enum MMTimeSlice {']
    lines += ['    MMT_%s,' % s for s in lg.time_slices]
    lines += ['    MMT_COUNT', '};', '',
              '// 2Ship\'s RandoOptionIds, in gMsTerminaOptions order (MergeShipTerminaData.cpp).', 'enum MMOption {']
    lines += ['    MMO_%s,' % o[3:] for o in mm.options]
    lines += ['    MMO_COUNT', '};', '', '// The values of 2Ship\'s option enums (Types.h).']
    for name in sorted(set(ENUM_OPTIONS.values())):
        for i, e in enumerate(mm.option_enums[name]):
            lines.append('constexpr int MM_%s = %d;' % (e, i))
    lines += ['', '} // namespace MsTermina', '']
    out[os.path.join(SOH_MS, 'MergeShipTerminaLogicGen.h')] = '\n'.join(lines)
    return out, stats, problems


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='verify only; do not write')
    args = ap.parse_args()

    mm = parse_mm()
    rows, aliases, skip_rg, skip_ri = parse_def()
    existing_rg = [r for r in soh_enum('RandomizerGet.h')]
    termina_inc = os.path.join(SOH_RANDO, 'randomizerEnums', 'RandomizerGetTermina.inc')
    if os.path.exists(termina_inc):  # our own earlier output is not "existing": regenerate it from the table
        ours = set(re.findall(r'RANDO_ENUM_ITEM\((\w+)', read(termina_inc)))
        existing_rg = [r for r in existing_rg if r not in ours]
    existing_rg = set(existing_rg)

    problems = check_table(mm, rows, aliases, skip_rg, skip_ri, existing_rg)
    if not problems:
        problems = check_camc(mm, rows, existing_rg)[0]
    in_regions = {c for cs in mm.region_checks.values() for c in cs}
    print('port_mm_rando: 2Ship: %d checks (%d listed by a region), %d item ids, %d regions, %d options' %
          (len(mm.check_ids), len(in_regions & set(mm.check_ids)), len(mm.item_ids), len(mm.region_ids),
           len(mm.options)))
    print('port_mm_rando: MsItems.def: %d items (%d shared/MM, %d with a proxy RI_OOT_*), %d aliases; %d RG_MM_* new'
          % (len(rows), sum(1 for r in rows if not r['proxy']), sum(1 for r in rows if r['proxy']), len(aliases),
             sum(1 for r in rows if r['rg'] not in existing_rg)))
    for p in problems:
        print('  PROBLEM: ' + p)
    if problems:
        return 1

    lg = parse_logic(mm)
    logic_files, stats, logic_problems = gen_logic_files(mm, lg)
    print('port_mm_rando: logic: %s' % ', '.join('%d %s' % (n, k) for k, n in stats.items()))
    for p in logic_problems:
        print('  PROBLEM: ' + p)
    if logic_problems:
        return 1

    files = gen_files(mm, rows, skip_ri, existing_rg)
    files.update(logic_files)
    stale = 0
    for path, text in files.items():
        old = read(path) if os.path.exists(path) else None
        if old == text:
            continue
        stale += 1
        if args.check:
            print('  STALE: ' + os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            print('  wrote ' + os.path.relpath(path, ROOT))
    if args.check:
        print('port_mm_rando: %s' % ('up to date' if stale == 0 else '%d generated file(s) out of date' % stale))
        return 1 if stale else 0
    print('port_mm_rando: %d file(s) written, %d unchanged' % (stale, len(files) - stale))
    return 0


if __name__ == '__main__':
    sys.exit(main())
