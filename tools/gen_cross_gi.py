def function_body(text, head):
    """The body of the definition of `head` (a prototype, which ends in ';' before any '{', is skipped)."""
    i = text.find(head)
    while i >= 0:
        j = text.find('{', i)
        if j >= 0 and ';' not in text[i:j]:
            break
        i = text.find(head, i + 1)
    if i < 0:
        return None
    depth = 0
    for k in range(j, len(text)):
        depth += text[k] == '{'
        depth -= text[k] == '}'
        if depth == 0:
            return text[j:k + 1]
    return None


def audit_draw_sites():
    problems = []
    for path, head, rx, what in DRAW_SITES:
        if not os.path.exists(path):
            problems.append('draw site %s: %s is missing' % (what, os.path.relpath(path, ROOT)))
            continue
        text = strip_comments(read(path))
        body = text if head is None else function_body(text, head)
        if body is None or not re.search(rx, body):
            problems.append('draw site %s: %s no longer draws the item\'s own model (%s)' %
                            (what, os.path.relpath(path, ROOT), head or rx))
    return problems


