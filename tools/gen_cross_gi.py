def parse_oot_draw():
    zdraw = read(os.path.join(SOH, 'src', 'code', 'z_draw.c'))
    body = strip_comments(table_body(zdraw, 'DrawItemTableEntry sDrawItemTable[] = {'))
    enum_text = read(os.path.join(SOH, 'include', 'z64item.h'))
    e = enum_text[:enum_text.index('} GetItemDrawID;')]
    e = e[e.rindex('typedef enum'):]
    gids = [g for g in re.findall(r'\b(GID_\w+)\b', strip_comments(e)) if g != 'GID_MAXIMUM']
    entries = re.findall(r'\{\s*GetItem_Draw(\w+)\s*,\s*\{(.*?)\}\s*\}', body, re.S)
    if len(entries) != len(gids):
        sys.exit('gen_cross_gi: OoT sDrawItemTable has %d rows, GetItemDrawID %d' % (len(entries), len(gids)))
    oot_paths = header_paths(os.path.join(SOH, 'assets', 'objects'), r'#define d(\w+) "__OTR__(objects/[^"]+)"')
    rows = []
    for gid, (func, res) in zip(gids, entries):
        rr = []
        for r in [x.strip() for x in res.split(',') if x.strip()]:
            name = r.lstrip('&')
            rr.append(None if name == 'NULL' else (name, resolve(oot_paths, name)))
        rows.append({'gid': gid, 'func': func, 'res': rr})
    return rows, oot_paths


