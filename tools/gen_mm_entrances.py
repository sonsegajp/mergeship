# ---- parsing -----------------------------------------------------------------------------------------------------------


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def entrance_scene_ids():
    text = strip_comments(read(os.path.join(MM, 'include', 'z64scene.h')))
    m = re.search(r'typedef enum\s*\{([^}]*)\}\s*EntranceSceneId\s*;', text)
    if not m:
        sys.exit('gen_mm_entrances: EntranceSceneId not found')
    ids = {}
    for i, name in enumerate(e.strip() for e in m.group(1).split(',') if e.strip()):
        ids[name.replace('ENTR_SCENE_', '')] = i
    return ids


class Regions:
    def __init__(self):
        self.scene = {}
        self.name = {}
        self.exits = {}  # region -> [(to, from)]
        self.checks = {}
        self.connections = {}  # region -> [region]
        self.one_way = {}  # region -> [entrance]
        files = sorted(f for f in os.listdir(os.path.join(MM_RANDO, 'Logic', 'Regions')) if f.endswith('.cpp'))
        texts = [read(os.path.join(MM_RANDO, 'Logic', 'Regions', f)) for f in files]
        texts.append(read(os.path.join(MM_RANDO, 'Logic', 'Logic.cpp')))
        ent = r'(ENTRANCE\(\s*\w+\s*,\s*\d+\s*\)|ONE_WAY_EXIT)'
        for text in texts:
            text = strip_comments(text)
            starts = list(re.finditer(r'Regions\[(RR_\w+)\]\s*=\s*RandoRegion\s*\{', text))
            for i, m in enumerate(starts):
                end = starts[i + 1].start() if i + 1 < len(starts) else len(text)
                body = text[m.end():end]
                region = m.group(1)
                sm = re.search(r'\.sceneId\s*=\s*(SCENE_\w+)', body)
                self.scene[region] = sm.group(1) if sm else 'SCENE_MAX'
                nm = re.search(r'\.name\s*=\s*"([^"]*)"', body)
                self.name[region] = nm.group(1) if nm else ''
                self.exits[region] = [(norm(a), norm(b)) for a, b in re.findall(r'\bEXIT\(\s*' + ent + r'\s*,\s*' + ent,
                                                                                body)]
                self.checks[region] = re.findall(r'\bCHECK\((RC_\w+)', body)
                self.connections[region] = re.findall(r'\bCONNECTION\(\s*(RR_\w+)', body)
                ow = re.search(r'\.oneWayEntrances\s*=\s*\{(.*?)\}\s*,?\s*(?:\.|\}\s*;)', body, re.S)
                self.one_way[region] = [norm(e) for e in re.findall(r'ENTRANCE\(\s*\w+\s*,\s*\d+\s*\)', ow.group(1))] \
                    if ow else []

    def display(self, region):
        """A readable name: the region id, with 2Ship's own name where it has one."""
        words = [w if w.isdigit() else w.capitalize() for w in region[3:].split('_')]
        base = ' '.join(words).replace('Of ', 'of ').replace('The ', 'the ')
        return base


def norm(e):
    return re.sub(r'\s+', '', e)


def parse_entrance(e):
    m = re.match(r'ENTRANCE\((\w+),(\d+)\)', e)
    return (m.group(1), int(m.group(2))) if m else None


def parse_checks():
    text = read(os.path.join(MM_RANDO, 'StaticData', 'Checks.cpp'))
    checks = {}
    for m in re.finditer(r'\bRC\((RC_\w+),\s*(RCTYPE_\w+),\s*(SCENE_\w+),\s*(FLAG_\w+),\s*([^,]+?),\s*(RI_\w+)\)', text):
        checks[m.group(1)] = {'type': m.group(2), 'scene': m.group(3), 'flagType': m.group(4),
                              'flag': m.group(5).strip(), 'item': m.group(6)}
    return checks


def parse_grotto_data_maps():
    """ActorBehavior/ObjGrass.cpp: 2Ship tells its generic grottos apart by the hole's respawn data (cowGrottoMap,
    chestGrottoMap: data -> a check of that grotto)."""
    text = strip_comments(read(os.path.join(MM_RANDO, 'ActorBehavior', 'ObjGrass.cpp')))
    out = {}
    for name in ('cowGrottoMap', 'chestGrottoMap'):
        m = re.search(name + r'\s*=\s*\{(.*?)\n\};', text, re.S)
        if not m:
            sys.exit('gen_mm_entrances: %s not found in ObjGrass.cpp' % name)
        for dm in re.finditer(r'\{\s*(-?\d+)\s*,\s*(?:\{\s*\d+\s*,\s*)?(RC_\w+)', m.group(1)):
            out[dm.group(2)] = int(dm.group(1)) & 0xFF
    return out


def parse_grotto_numbering():
    """Logic.cpp GetRegionIdFromEntrance: runtime GROTTOS spawn -> {2Ship grotto number: outside scene}."""
    text = strip_comments(read(os.path.join(MM_RANDO, 'Logic', 'Logic.cpp')))
    fn = text[text.index('GetRegionIdFromEntrance(s32 entrance)'):]
    fn = fn[:fn.index('entranceToRegionId.contains(modifiedEntrance)')]
    out = {}
    for block in re.finditer(r'entrance\s*==\s*ENTRANCE\(GROTTOS,\s*(\d+)\)\)\s*\{(.*?)\n\s{4}\}', fn, re.S):
        spawn = int(block.group(1))
        for case in re.finditer(r'case\s+ENTRANCE\((\w+),\s*0\):\s*modifiedEntrance\s*=\s*([^;]+);', block.group(2)):
            for n in re.findall(r'ENTRANCE\(GROTTOS,\s*(\d+)\)', case.group(2)):
                out[int(n)] = (spawn, case.group(1))
    if not out:
        sys.exit('gen_mm_entrances: no grotto numbering found in Logic.cpp')
    return out


# ---- building ----------------------------------------------------------------------------------------------------------


class Gen:
    def __init__(self):
        self.ids = entrance_scene_ids()
        self.regions = Regions()
        self.checks = parse_checks()
        self.numbering = parse_grotto_numbering()
        self.data_maps = parse_grotto_data_maps()
        self.problems = []

    def value(self, scene, spawn):
        if scene not in self.ids:
            sys.exit('gen_mm_entrances: unknown entrance scene %s' % scene)
        return ((self.ids[scene] & 0x7F) << 9) | ((spawn & 0x1F) << 4)

    def key(self, scene, spawn):
        return 0x4000 | ((self.value(scene, spawn) >> 4) & 0x0FFF)

    def has_exit(self, region, to, frm=None):
        for a, b in self.regions.exits.get(region, []):
            if a == to and (frm is None or b == frm):
                return True
        return False

    def ent(self, se):
        return 'ENTRANCE(%s,%d)' % se

    def check_pair(self, outside, inside, into, back):
        if not self.has_exit(outside, self.ent(into), self.ent(back)):
            self.problems.append('%s has no EXIT(%s, %s)' % (outside, self.ent(into), self.ent(back)))
        if not self.has_exit(inside, self.ent(back), self.ent(into)):
            self.problems.append('%s has no EXIT(%s, %s)' % (inside, self.ent(back), self.ent(into)))

    def grottos(self):
        """Every grotto region (scene SCENE_KAKUSIANA) with its way out, and the region whose exit leads in."""
        out = []
        for region, exits in self.regions.exits.items():
            if self.regions.scene.get(region) != 'SCENE_KAKUSIANA':
                continue
            for to, frm in exits:
                g = parse_entrance(frm)
                if not g or g[0] != 'GROTTOS':
                    continue
                n = g[1]
                outside = [r for r, ex in self.regions.exits.items() if r != region and
                           any(a == frm for a, _ in ex)]
                if len(outside) != 1:
                    self.problems.append('grotto %d (%s): %d regions lead in' % (n, region, len(outside)))
                    continue
                out.append((n, outside[0], region, parse_entrance(to)))
        out.sort()
        seen = set()
        for n, _, region, _ in out:
            if n in seen:
                self.problems.append('grotto %d listed twice' % n)
            seen.add(n)
        return out

    # ---- overworld and interiors ----------------------------------------------------------------------------------

    def season(self, e):
        """An entrance ('ENTRANCE(SCENE,n)') in the regions' own season (winter, poisoned): how 2Ship's runtime
        view compares them (MM's exits may name either)."""
        p = parse_entrance(e)
        if p and p[0] in SEASON_ENTRANCES:
            return 'ENTRANCE(%s,%d)' % (SEASON_ENTRANCES[p[0]], p[1])
        return e

    def claims(self):
        """entrance -> the regions it arrives in (an exit's `from`, or a oneWayEntrances entry)."""
        out = {}
        for region, exits in self.regions.exits.items():
            for to, frm in exits:
                if frm != 'ONE_WAY_EXIT':
                    out.setdefault(frm, set()).add(region)
        for region, entrances in self.regions.one_way.items():
            for e in entrances:
                out.setdefault(e, set()).add(region)
        return out

    def ways_to(self, region, target, claims):
        """How many exits and connections of `region` lead into `target` (the port makes them one SoH exit)."""
        n = sum(1 for to, _ in self.regions.exits.get(region, []) if target in claims.get(to, ()))
        return n + sum(1 for c in self.regions.connections.get(region, []) if c == target)

    def scene_exits_to(self, scene, entrance):
        """Every exit, of any region of `scene`, into `entrance`."""
        return [(r, to) for r, exits in self.regions.exits.items() if self.regions.scene.get(r) == scene
                for to, _ in exits if self.season(to) == self.season(entrance)]

    def pairs(self):
        """The two-way overworld and interior connections: (kind, a, b, into b, into a); kind 'overworld' (a, b
        overworld) or 'interior' (a the overworld side, b the interior). Also the left-out ones, with the reason."""
        claims = self.claims()
        found, left, seen = [], [], set()
        for a in sorted(self.regions.exits):
            sa = self.regions.scene.get(a)
            if sa not in OVERWORLD_SCENES and sa not in INTERIOR_SCENES:
                continue
            for to, frm in self.regions.exits[a]:
                if frm == 'ONE_WAY_EXIT' or not parse_entrance(to):
                    continue
                into_b, into_a = to, frm
                owners_b = claims.get(into_b, set())
                if len(owners_b) != 1:
                    continue
                b = next(iter(owners_b))
                sb = self.regions.scene.get(b)
                if sa in OVERWORLD_SCENES and sb in OVERWORLD_SCENES:
                    kind = 'overworld'
                elif sa in OVERWORLD_SCENES and sb in INTERIOR_SCENES:
                    kind = 'interior'
                elif sa in INTERIOR_SCENES and sb in OVERWORLD_SCENES:
                    continue  # found from the overworld side
                else:
                    continue
                ident = frozenset((into_a, into_b))
                if ident in seen:
                    continue
                seen.add(ident)
                name = '%s <-> %s' % (a, b)
                reason = LEFT_OUT.get(frozenset((a, b)))
                if reason is None and sa == sb:
                    reason = 'both sides are in %s (a passage within one scene)' % sa
                if reason is None and claims.get(into_a, set()) != {a}:
                    reason = '%s arrives in %s' % (into_a, ', '.join(sorted(claims.get(into_a, set()))) or 'no region')
                if reason is None and not any(t == into_a and f == into_b for t, f in self.regions.exits.get(b, [])):
                    reason = '%s has no way back EXIT(%s, %s)' % (b, into_a, into_b)
                if reason is None and self.ways_to(a, b, claims) != 1:
                    reason = '%s reaches %s %d ways (one SoH exit)' % (a, b, self.ways_to(a, b, claims))
                if reason is None and self.ways_to(b, a, claims) != 1:
                    reason = '%s reaches %s %d ways (one SoH exit)' % (b, a, self.ways_to(b, a, claims))
                if reason is None and len(self.scene_exits_to(sa, into_b)) != 1:
                    reason = 'another exit of %s also leads to %s' % (sa, into_b)
                if reason is None and len(self.scene_exits_to(sb, into_a)) != 1:
                    reason = 'another exit of %s also leads to %s' % (sb, into_a)
                if reason is not None:
                    left.append((kind, name, reason))
                    continue
                found.append((kind, a, b, parse_entrance(into_b), parse_entrance(into_a)))
        return found, left

    def me_entrance(self, se):
        """(scene, spawn) as a MS_ME_* row's entrance, in the regions' own season."""
        return 'ENTRANCE(%s, %d)' % parse_entrance(self.season(self.ent(se)))

    def grotto_data(self, region):
        mapped = [self.data_maps[rc] for rc in self.regions.checks.get(region, []) if rc in self.data_maps]
        chest = self.chest_data(region)
        if mapped:
            if chest is not None and chest != mapped[0]:
                self.problems.append('%s: chest data 0x%02X, ObjGrass.cpp says 0x%02X' % (region, chest, mapped[0]))
            return mapped[0]
        return chest

    def chest_data(self, region):
        for rc in self.regions.checks.get(region, []):
            c = self.checks.get(rc)
            if c and c['type'] == 'RCTYPE_CHEST' and c['flagType'] == 'FLAG_CYCL_SCENE_CHEST':
                if c['item'] not in CHEST_CONTENTS:
                    self.problems.append('%s: chest item %s has no grotto content index' % (rc, c['item']))
                    return None
                return (CHEST_CONTENTS[c['item']] << 5) | (int(c['flag'], 0) & 0x1F)
        return None

    def build(self):
        g = self
        soh, trk, mm = [], [], []
        hdr = '// MergeShip2: ' + GEN_NOTE
        soh += [hdr,
                '// Termina\'s shuffleable entrances as SoH regions (soh/MergeShip/MergeShipEntrances.cpp; keys:',
                '// include/mergeship/MsEntrances.h). Included with the MS_TE_* macros defined.',
                '//',
                '// MS_TE_DUNGEON(id, outsideRR, insideRR, keyIn, keyOut, outsideName, insideName)',
                '// MS_TE_BOSS(boss, preBossRR, lairRR, keyDoor, keyReturn, returnRR, warpRR, keyWarp, dungeonId,',
                '//            ageAdult, doorName, lairName)',
                '// MS_TE_GROTTO(n, outsideRR, grottoRR, keyIn, keyReturn, outsideName, grottoName)',
                '// MS_TE_OVERWORLD(aRR, bRR, keyIntoB, keyIntoA, nameAtoB, nameBtoA): a two-way overworld connection',
                '// MS_TE_INTERIOR(outsideRR, insideRR, keyIn, keyOut, doorName, insideName): a door between the',
                '//            overworld and a house, shop, fountain or the like',
                '// MS_TE_MOON(index, fromRR, toRR, key, exitName, destinationName): one way; 0-3 the moon children\'s',
                '//            trial warps (from the moon field), 4 the Clock Tower rooftop\'s Oath to Order warp',
                '// MS_TE_REGION(rr, name, mmScene): every region above, named (for a region the logic port has not built',
                '//            yet), with its Majora\'s Mask scene (an entrance never leads back into its own scene)',
                '// clang-format off']
        trk += [hdr,
                '// Termina\'s rows of the entrance tracker\'s entranceData (randomizer_entrance_tracker.cpp), also the',
                '// names the spoiler log gives them. Included inside that array.',
                '// clang-format off']
        mm += [hdr,
               '// 2Ship\'s runtime view of Termina\'s shuffleable entrances (2s2h/MergeShip/MergeShipEntrances.cpp;',
               '// keys: include/mergeship/MsEntrances.h). Included with the MS_ME_* macros defined.',
               '//',
               '// MS_ME_EXIT(key, fromScene, mmEntrance): leaving fromScene through mmEntrance is taking entrance `key`',
               '// MS_ME_ARRIVE(key, mmEntrance): where a key arrives when nothing more is needed',
               '// MS_ME_GROTTO(n, runtimeEntrance, data, hasData, outsideEntrance, outsideAltEntrance, returnEntrance)',
               '//     n: 2Ship\'s grotto number; runtimeEntrance: the spawn MM loads; data: the respawn data a hole',
               '//     gives (generic grottos\' chest); outside*: the scene the hole is in (as ENTRANCE(scene, 0));',
               '//     returnEntrance: where 2Ship\'s logic leaves the grotto to (used when no hole is recorded)',
               '// MS_ME_BOSS(boss, lairScene, doorScene, keyWarp, warpEntrance, warpAltEntrance, dungeonEntrance,',
               '//            clearedFlag)',
               '// clang-format off']

        # Dungeons
        for i, (name, outside, inside, into, back) in enumerate(DUNGEONS):
            g.check_pair(outside, inside, into, back)
            kin, kout = g.key(*into), g.key(*back)
            oname = 'MM ' + name + ' Entryway'
            iname = 'MM ' + name
            dname = 'MM ' + g.regions.display(outside) + ' (' + name + ')'
            soh.append('MS_TE_DUNGEON(%d, RR_MM_%s, RR_MM_%s, 0x%04X, 0x%04X, %s, %s)' %
                       (i, outside[3:], inside[3:], kin, kout, cstr(dname), cstr(iname)))
            trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                       'ENTRANCE_TYPE_DUNGEON, "mm,termina", 1},' % (kin, kout, cstr(dname), cstr(iname)))
            trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                       'ENTRANCE_TYPE_DUNGEON, "mm,termina"},' % (kout, kin, cstr(oname), cstr(dname)))
            mm.append('MS_ME_EXIT(0x%04X, %s, ENTRANCE(%s, %d))' % (kin, g.regions.scene[outside], *into))
            mm.append('MS_ME_EXIT(0x%04X, %s, ENTRANCE(%s, %d))' % (kout, g.regions.scene[inside], *back))
            mm.append('MS_ME_ARRIVE(0x%04X, ENTRANCE(%s, %d))' % (kin, *into))
            mm.append('MS_ME_ARRIVE(0x%04X, ENTRANCE(%s, %d))' % (kout, *back))

        # Bosses
        for (b, boss, di, preboss, lair, door, lairScene, warpRegion, warp, altWarps, pool, flag) in BOSSES:
            dname, doutside, dinside, dinto, dback = DUNGEONS[di]
            if not g.has_exit(preboss, g.ent(door)):
                self.problems.append('%s has no EXIT(%s, ...)' % (preboss, g.ent(door)))
            if not g.has_exit(lair, g.ent(warp)):
                self.problems.append('%s has no EXIT(%s, ...) (its blue warp)' % (lair, g.ent(warp)))
            kdoor, kret, kwarp = g.key(*door), 0x5100 | b, g.key(*warp)
            doorName = 'MM ' + dname + ' Boss Door'
            lairName = 'MM ' + boss + "'s Lair"
            soh.append('MS_TE_BOSS(%d, RR_MM_%s, RR_MM_%s, 0x%04X, 0x%04X, RR_MM_%s, RR_MM_%s, 0x%04X, %d, %d, %s, %s)' %
                       (b, preboss[3:], lair[3:], kdoor, kret, dinside[3:], warpRegion[3:], kwarp, di,
                        1 if pool == 'AdultBoss' else 0, cstr(doorName), cstr(lairName)))
            trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                       'ENTRANCE_TYPE_DUNGEON, "mm,termina,boss", 1},' % (kdoor, kret, cstr(doorName), cstr(lairName)))
            trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                       'ENTRANCE_TYPE_DUNGEON, "mm,termina,boss", 1},' %
                       (kret, kdoor, cstr(lairName), cstr('MM ' + dname + ' Entryway')))
            trk.append('{ 0x%04X, -1, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                       'ENTRANCE_TYPE_ONE_WAY, "mm,termina,bw", 1},' %
                       (kwarp, cstr('MM ' + boss + ' Blue Warp'), cstr('MM ' + dname + ' Blue Warp')))
            mm.append('MS_ME_EXIT(0x%04X, %s, ENTRANCE(%s, %d))' % (kdoor, g.regions.scene[preboss], *door))
            mm.append('MS_ME_ARRIVE(0x%04X, ENTRANCE(%s, %d))' % (kdoor, *door))
            mm.append('MS_ME_ARRIVE(0x%04X, ENTRANCE(%s, %d))' % (kwarp, *warp))
            alt = 'ENTRANCE(%s, %d)' % altWarps[0] if altWarps else '0xFFFF'
            mm.append('MS_ME_BOSS(%d, %s, %s, 0x%04X, ENTRANCE(%s, %d), %s, ENTRANCE(%s, %d), %s)' %
                      (b, lairScene, g.regions.scene[preboss], kwarp, warp[0], warp[1], alt, dinto[0], dinto[1], flag))

        # Grottos
        for n, outside, grotto, ret in g.grottos():
            kin, kret = g.key('GROTTOS', n), 0x5000 | n
            gname = 'MM ' + (g.regions.name.get(grotto) or g.regions.display(grotto))
            if not gname.endswith('Grotto') and not gname.endswith('Shrine'):
                gname += ' Grotto'
            oname = 'MM ' + g.regions.display(outside) + ' (' + gname[3:] + ')'
            soh.append('MS_TE_GROTTO(%d, RR_MM_%s, RR_MM_%s, 0x%04X, 0x%04X, %s, %s)' %
                       (n, outside[3:], grotto[3:], kin, kret, cstr(oname), cstr(gname)))
            trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                       'ENTRANCE_TYPE_GROTTO, "mm,termina", 1},' % (kin, kret, cstr(oname), cstr(gname)))
            trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                       'ENTRANCE_TYPE_GROTTO, "mm,termina"},' % (kret, kin, cstr(gname), cstr(oname)))
            if n in g.numbering:
                spawn, scene = g.numbering[n]
                data = g.grotto_data(grotto)
            else:
                spawn, scene, data = n, ret[0], None
            alt = SCENE_ALIASES.get(scene)
            mm.append('MS_ME_GROTTO(%d, ENTRANCE(GROTTOS, %d), 0x%02X, %d, ENTRANCE(%s, 0), %s, ENTRANCE(%s, %d))' %
                      (n, spawn, data or 0, 1 if data is not None else 0, scene,
                       'ENTRANCE(%s, 0)' % alt if alt else '0xFFFF', ret[0], ret[1]))
            if n == 19 and data != 0x3F:
                self.problems.append('grotto 19 data 0x%X, 2Ship expects 0x3F (Logic.cpp)' % (data or 0))

        # Overworld and interiors (found in 2Ship's regions: Gen.pairs)
        found, left = g.pairs()
        for kind, a, b, into_b, into_a in found:
            kb, ka = g.key(*into_b), g.key(*into_a)
            da, db = g.regions.display(a), g.regions.display(b)
            if kind == 'overworld':
                ab, ba = 'MM %s -> %s' % (da, db), 'MM %s -> %s' % (db, da)
                soh.append('MS_TE_OVERWORLD(RR_MM_%s, RR_MM_%s, 0x%04X, 0x%04X, %s, %s)' %
                           (a[3:], b[3:], kb, ka, cstr(ab), cstr(ba)))
                trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                           'ENTRANCE_TYPE_OVERWORLD, "mm,termina"},' %
                           (kb, ka, cstr(ab), cstr('MM %s (from %s)' % (db, da))))
                trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                           'ENTRANCE_TYPE_OVERWORLD, "mm,termina"},' %
                           (ka, kb, cstr(ba), cstr('MM %s (from %s)' % (da, db))))
            else:
                door, inside = 'MM %s (%s)' % (da, db), 'MM ' + db
                soh.append('MS_TE_INTERIOR(RR_MM_%s, RR_MM_%s, 0x%04X, 0x%04X, %s, %s)' %
                           (a[3:], b[3:], kb, ka, cstr(door), cstr(inside)))
                trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                           'ENTRANCE_TYPE_INTERIOR, "mm,termina", 1},' % (kb, ka, cstr(door), cstr(inside)))
                trk.append('{ 0x%04X, 0x%04X, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                           'ENTRANCE_TYPE_INTERIOR, "mm,termina"},' % (ka, kb, cstr(inside), cstr(door)))
            mm.append('MS_ME_EXIT(0x%04X, %s, %s)' % (kb, g.regions.scene[a], g.me_entrance(into_b)))
            mm.append('MS_ME_EXIT(0x%04X, %s, %s)' % (ka, g.regions.scene[b], g.me_entrance(into_a)))
            mm.append('MS_ME_ARRIVE(0x%04X, %s)' % (kb, g.me_entrance(into_b)))
            mm.append('MS_ME_ARRIVE(0x%04X, %s)' % (ka, g.me_entrance(into_a)))
        soh.append('// %d overworld and %d interior pairs; left out:' %
                   (sum(1 for f in found if f[0] == 'overworld'), sum(1 for f in found if f[0] == 'interior')))
        for kind, name, reason in sorted(set(left)):
            soh.append('//   %s %s: %s' % (kind, name, reason))

        # The moon (one way): the children's trial warps, the rooftop's Oath to Order warp
        moon = [(i, MOON_FIELD, region, warp, 'MM Moon Child (%s)' % name, 'MM ' + name)
                for i, name, region, warp in MOON_TRIALS]
        moon.append((MOON_ROOF_INDEX, MOON_ROOF[0], MOON_FIELD, MOON_ROOF[1], 'MM Clock Tower Roof (Oath to Order)',
                     'MM The Moon'))
        claims = g.claims()
        for i, frm, to, warp, xname, dname in moon:
            if not g.has_exit(frm, g.ent(warp)):
                self.problems.append('%s has no EXIT(%s, ...) (the moon)' % (frm, g.ent(warp)))
            owners = claims.get(g.ent(warp), set())
            if owners != {to}:
                self.problems.append('%s arrives in %s, not %s (the moon)' % (g.ent(warp), sorted(owners), to))
            if len(g.scene_exits_to(g.regions.scene[frm], g.ent(warp))) != 1:
                self.problems.append('%s leaves to %s more than once (the moon)' % (g.regions.scene[frm], g.ent(warp)))
            if g.ways_to(frm, to, claims) != 1:
                self.problems.append('%s reaches %s more than one way (the moon)' % (frm, to))
            k = g.key(*warp)
            soh.append('MS_TE_MOON(%d, RR_MM_%s, RR_MM_%s, 0x%04X, %s, %s)' %
                       (i, frm[3:], to[3:], k, cstr(xname), cstr(dname)))
            trk.append('{ 0x%04X, -1, {{ -1 }}, %s, %s, ENTRANCE_GROUP_TERMINA, ENTRANCE_GROUP_TERMINA, '
                       'ENTRANCE_TYPE_ONE_WAY, "mm,termina,moon", 1},' % (k, cstr(xname), cstr(dname)))
            mm.append('MS_ME_EXIT(0x%04X, %s, %s)' % (k, g.regions.scene[frm], g.me_entrance(warp)))
            mm.append('MS_ME_ARRIVE(0x%04X, %s)' % (k, g.me_entrance(warp)))

        # One key per entrance and one key per (scene, exit): 2Ship's runtime tells exits apart by those.
        seen_keys = {}
        for line in soh:
            m = re.match(r'MS_TE_(\w+)\((.*)\)$', line)
            if not m or m.group(1) == 'REGION':
                continue
            for k in set(re.findall(r'\b0x([0-9A-F]{4})\b', m.group(2))):
                if k in seen_keys:
                    self.problems.append('key 0x%s is used twice (%s, %s)' % (k, seen_keys[k], line[:60]))
                seen_keys[k] = line[:60]
        exits = {}
        for line in mm:
            m = re.match(r'MS_ME_EXIT\((0x[0-9A-F]{4}), (\w+), (ENTRANCE\(\w+, \d+\))\)$', line)
            if m:
                exits.setdefault((m.group(2), m.group(3)), set()).add(m.group(1))
        for (scene, entrance), ks in sorted(exits.items()):
            if len(ks) > 1:
                self.problems.append('%s leaves to %s as several keys %s' % (scene, entrance, sorted(ks)))

        referenced = []
        for line in soh:
            for rr in re.findall(r'\bRR_MM_(\w+)', line):
                if rr not in referenced:
                    referenced.append(rr)
        for rr in referenced:
            soh.append('MS_TE_REGION(RR_MM_%s, %s, %s)' % (rr, cstr('MM ' + g.regions.display('RR_' + rr)),
                                                            cstr(g.regions.scene.get('RR_' + rr, 'SCENE_MAX'))))
        soh.append('// clang-format on')
        trk.append('// clang-format on')
        mm.append('// clang-format on')
        return {
            os.path.join(SOH_MS, 'MergeShipTerminaEntranceData.inc'): '\n'.join(soh) + '\n',
            os.path.join(SOH_MS, 'MergeShipTerminaTrackerData.inc'): '\n'.join(trk) + '\n',
            os.path.join(MM_MS, 'MergeShipEntranceData.inc'): '\n'.join(mm) + '\n',
        }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='verify only; do not write')
    args = ap.parse_args()
    gen = Gen()
    files = gen.build()
    for p in gen.problems:
        print('gen_mm_entrances: ' + p)
    bad = bool(gen.problems)
    for path, text in files.items():
        old = read(path) if os.path.exists(path) else None
        if old == text:
            continue
        if args.check:
            print('gen_mm_entrances: out of date: ' + os.path.relpath(path, ROOT))
            bad = True
        else:
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            print('gen_mm_entrances: wrote ' + os.path.relpath(path, ROOT))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
