def parse_mm_draw():
    zdraw = read(os.path.join(MM_SRC, 'src', 'code', 'z_draw.c'))
    body = table_body(zdraw, 'static DrawItemTableEntry sDrawItemTable[] = {')
    mm_paths = header_paths(os.path.join(SOH, 'assets', 'mm'), r'#define dmm_(\w+) "__OTR__(mm/[^"]+)"')
    rows = []
    for m in re.finditer(r'//\s*(GID_\w+)(?:,\s*(OBJECT_\w+))?[^\n]*\n\s*\{\s*GetItem_Draw(\w+)\s*,\s*\{(.*?)\}\s*\}\s*,',
                         body, re.S):
        gid, obj, func = m.group(1), (m.group(2) or '').lower() or None, m.group(3)
        res = []
        for r in [x.strip() for x in m.group(4).split(',') if x.strip()]:
            name = r.lstrip('&')
            res.append(None if name == 'NULL' else (name, resolve(mm_paths, name, obj)))
        rows.append({'gid': gid, 'func': func, 'res': res})
    # The table is indexed by MM's GetItemDrawId: its rows must be that enum, in order.
    z64item = read(os.path.join(MM_SRC, 'include', 'z64item.h'))
    e = z64item[:z64item.index('} GetItemDrawId;')]
    e = strip_comments(e[e.rindex('typedef enum'):])
    enum = [g for g in re.findall(r'\b(GID_\w+)\b', e) if g not in ('GID_NONE', 'GID_MAX', 'GID_MAXIMUM')]
    if [r['gid'] for r in rows] != enum[:len(rows)] or len(enum) != len(rows):
        sys.exit('gen_cross_gi: MM sDrawItemTable rows (%d) do not follow GetItemDrawId (%d)' % (len(rows), len(enum)))
    return rows


def parse_drawitem_kinds():
    """RandoItemId -> the 2Ship draw (a TERMINA_KINDS name, or Progressive/Junk/Trap/None/Other:<fn>)."""
    text = strip_comments(read(os.path.join(MM_RANDO, 'DrawItem.cpp')))
    fn = text.index('void Rando::DrawItem(')
    sw = text.index('switch (randoItemId) {', text.index('IsProxy', fn))
    depth, i = 0, text.index('{', sw)
    for j in range(i, len(text)):
        depth += text[j] == '{'
        depth -= text[j] == '}'
        if depth == 0:
            break
    body = text[i + 1:j]
    kinds, default = {}, 'MMGid'
    for seg in body.split('break;'):
        labels = list(re.finditer(r'case\s+(RI_\w+)\s*:|default\s*:', seg))
        if not labels:
            continue
        rest = seg[labels[-1].end():]
        call = re.match(r'\s*((?:\w+::)*\w+)\s*\(', rest)
        if not call:
            kind = 'None'
        else:
            name = call.group(1)
            if name == 'Rando::DrawItem':
                kind = ('Progressive' if 'ConvertItem' in rest else 'Junk' if 'CurrentJunkItem' in rest
                        else 'Trap' if 'CurrentTrapItem' in rest else 'Other:' + name)
            elif name == 'GetItem_Draw':
                kind = 'MMGid'
            elif name in TERMINA_KINDS or name in ('DrawSoul',):
                kind = name
            else:
                kind = 'Other:' + name
        for lab in labels:
            if lab.group(1):
                kinds[lab.group(1)] = kind
            else:
                default = kind
    for ri, fn_name in re.findall(r'\{\s*(RI_SOUL_\w+),\s*(Draw\w+)\s*\}', text):
        kinds[ri] = fn_name
    return kinds, default


def termina_rows(mm_gi):
    d = read(DEF)
    rg_ri = dict(re.findall(r'^MS_ITEM\(\w+,\s*(RG_\w+),\s*(RI_\w+),', d, re.M))
    names = dict(re.findall(r'^MS_ITEM\(\w+,\s*(RG_\w+),\s*RI_\w+,\s*MS_KIND_\w+,\s*MS_\w+,\s*\d,\s*\d,\s*\d+,\s*"((?:[^"\\]|\\.)*)"\)',
                            d, re.M))
    generated = re.findall(r'RANDO_ENUM_ITEM\((RG_\w+)\)',
                           read(os.path.join(SOH_RANDO, 'randomizerEnums', 'RandomizerGetTermina.inc')))
    items = read(os.path.join(MM_RANDO, 'StaticData', 'Items.cpp'))
    draw_id = dict(re.findall(r'\bRI\((RI_\w+),.*?,\s*(GID_\w+)\)', items))
    kinds, default = parse_drawitem_kinds()
    gids = {r['gid'] for r in mm_gi}
    rows, problems = [], []
    for rg in generated:
        ri = rg_ri.get(rg)
        if ri is None:
            problems.append('%s: no MS_ITEM row' % rg)
            continue
        kind = kinds.get(ri, default)
        gid = draw_id.get(ri, 'GID_NONE')
        if kind == 'DrawSoul':
            kind = 'Other:DrawSoul'
        if (kind == 'Progressive') and (ri in MM_PROGRESSIVE_GID):
            kind, gid = 'MMGid', MM_PROGRESSIVE_GID[ri]
        if kind not in TERMINA_KINDS:
            problems.append('%s (%s): 2Ship draws it with %s, which MergeShipTerminaGiDraw.cpp does not port' %
                            (rg, ri, kind))
        if kind == 'MMGid' and gid not in gids:
            problems.append('%s (%s): drawId %s is not in MM\'s sDrawItemTable' % (rg, ri, gid))
        rows.append({'rg': rg, 'ri': ri, 'kind': kind, 'gid': gid, 'name': names.get(rg, rg)})
    return rows, problems


def gen_soh(mm_gi, trows):
    lines = ['// MergeShip2: ' + GEN_NOTE,
             '// Included once by MergeShipTerminaGiDraw.cpp, which defines MsMMGiRow, MsTerminaGiRow and the',
             '// MSMMGI_* / MSTGI_* enums (no include guard).', '',
             "// Majora's Mask's get-item draw table (2Ship mm/src/code/z_draw.c sDrawItemTable), its resources as mm.o2r",
             '// paths.']
    names = {}
    problems = []
    for r in mm_gi:
        r['idents'] = []
        for x in r['res']:
            if x is None or x[1] is None:
                if x is not None:
                    problems.append('MM %s: %s is not in SoH\'s mm asset headers' % (r['gid'], x[0]))
                r['idents'].append('nullptr')
                continue
            name, path = x
            ident = 'kMmGi_' + name
            if ident in names and names[ident] != path:
                ident = 'kMmGi_%s_%d' % (name, len(names))
            names.setdefault(ident, path)
            r['idents'].append(ident)
    for ident, path in sorted(names.items()):
        lines.append('static const ALIGN_ASSET(2) char %s[] = "__OTR__%s";' % (ident, path))
    lines += ['', 'enum MsMMGid : s16 {', '    MSMMGID_NONE = -1,']
    for r in mm_gi:
        lines.append('    MSMMGID_%s,' % r['gid'][4:])
    lines += ['    MSMMGID_COUNT', '};', '', 'static const MsMMGiRow kMsMMGiTable[MSMMGID_COUNT] = {']
    for r in mm_gi:
        if r['func'] not in MM_GI_FUNCS:
            problems.append('MM %s: draw function GetItem_Draw%s is not ported' % (r['gid'], r['func']))
        lines.append('    /* %-22s */ { MSMMGI_%s, { %s } },' % (r['gid'], r['func'], ', '.join(r['idents']) or 'nullptr'))
    lines += ['};', '', '// The Termina items SoH generated (item_list_termina.cpp) and how 2Ship\'s Rando::DrawItem draws each',
              '// (DrawItem.cpp): its special draw, or MM\'s GetItem_Draw of its RandoItemId\'s drawId.',
              'static const MsTerminaGiRow kMsTerminaGiRows[] = {']
    for t in trows:
        gid = 'MSMMGID_' + t['gid'][4:] if t['gid'] != 'GID_NONE' else 'MSMMGID_NONE'
        lines.append('    { %s, MSTGI_%s, %s }, // %s' % (t['rg'], t['kind'], gid, t['ri']))
    lines += ['};', '']
    return '\n'.join(lines), problems


