def read(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        return f.read()


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def header_paths(base, pattern):
    """name -> [paths] from every generated asset header under `base`."""
    out = collections.defaultdict(list)
    rx = re.compile(pattern)
    for dirpath, _, files in os.walk(base):
        for f in files:
            if f.endswith('.h'):
                for m in rx.finditer(read(os.path.join(dirpath, f))):
                    if m.group(2) not in out[m.group(1)]:
                        out[m.group(1)].append(m.group(2))
    return out


def resolve(paths, name, obj=None):
    cands = paths.get(name, [])
    if obj:
        for p in cands:
            if '/%s/' % obj in p:
                return p
    return cands[0] if cands else None


def table_body(text, start_marker):
    i = text.index(start_marker)
    j = text.index('\n};', i)
    return text[i + len(start_marker):j]


