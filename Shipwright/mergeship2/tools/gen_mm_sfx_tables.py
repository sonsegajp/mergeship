# MergeShip2: regenerate Shipwright/soh/soh/MergeShip/MergeShipMMSfxTables.inc.
#
# 1. Majora's Mask's per-sfx parameters (importance, flags2, params), one table per sfx bank, copied from
#    2ship2harkinian/mm/include/tables/sfx/*bank_table.h exactly as MM's sfx_params.c builds gSfxParams.
# 2. The Ocarina of Time -> Majora's Mask sfx id map used for MM forms: an OoT NA_SE_ id maps to the MM
#    NA_SE_ id with the same name (Shipwright/soh/include/sfx.h vs 2ship2harkinian/mm/include/sfx.h),
#    plus the few sounds MM renamed (ALIASES).
import os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
mm_tables = os.path.join(root, '2ship2harkinian/mm/include/tables/sfx')
oot_sfx = os.path.join(root, 'Shipwright/soh/include/sfx.h')
mm_sfx = os.path.join(root, '2ship2harkinian/mm/include/sfx.h')
out = os.path.join(root, 'Shipwright/soh/soh/MergeShip/MergeShipMMSfxTables.inc')

# MM gSfxParams order (sfx_params.c): player, item, environment, enemy, system, ocarina, voice.
BANKS = [('Player', 'playerbank_table.h'), ('Item', 'itembank_table.h'), ('Env', 'environmentbank_table.h'),
         ('Enemy', 'enemybank_table.h'), ('System', 'systembank_table.h'), ('Ocarina', 'ocarinabank_table.h'),
         ('Voice', 'voicebank_table.h')]

# OoT name -> MM name, where MM renamed the same sound (same id, same use in the player's animation lists).
ALIASES = {
    'NA_SE_PL_JUMP': 'NA_SE_PL_JUMP_GROUND',
    'NA_SE_PL_LAND': 'NA_SE_PL_LAND_GROUND',
    'NA_SE_IT_SHIELD_POSTURE': 'NA_SE_IT_SHIELD_SWING',
}


def load_ids(path):
    ids = {}
    for line in open(path, encoding='utf-8'):
        m = re.match(r'#define (NA_SE_\w+)\s+(0x[0-9A-Fa-f]+|\d+)\s*$', line.strip())
        if m:
            ids[m.group(1)] = int(m.group(2), 0)
    return ids


def mm_flags(expr):
    expr = expr.strip()
    expr = re.sub(r'\bSFX_FLAG2_', 'MMSFX_FLAG2_', expr)
    expr = re.sub(r'\bSFX_FLAG_', 'MMSFX_FLAG_', expr)
    expr = re.sub(r'\bSFX_PARAM_', 'MMSFX_PARAM_', expr)
    return expr


lines = []
lines.append('// MergeShip2 -- generated by tools/gen_mm_sfx_tables.py from 2ship2harkinian/mm/include/tables/sfx/*.h,')
lines.append('// 2ship2harkinian/mm/include/sfx.h and Shipwright/soh/include/sfx.h. Do not edit.')
lines.append('// Included only by MergeShipMMSfx.c, which defines MMSfxParams and the MMSFX_* flags.')
lines.append('')
for name, fname in BANKS:
    lines.append(f'static const MMSfxParams sMM{name}BankParams[] = {{')
    count = 0
    for line in open(os.path.join(mm_tables, fname), encoding='utf-8'):
        m = re.search(r'DEFINE_SFX\((\w+),(.*)\)\s*$', line.strip())
        if not m:
            continue
        args = [a.strip() for a in m.group(2).split(',')]
        assert len(args) == 5, line
        importance, dist, rand, flags2, flags1 = args
        # MM sfx_params.c DEFINE_SFX
        lines.append(f'    /* {m.group(1)} */ {{ {importance}, {mm_flags(flags2)}, '
                     f'((({dist}) << MMSFX_PARAM_DIST_RANGE_SHIFT) & MMSFX_PARAM_DIST_RANGE_MASK) | '
                     f'((({rand}) << MMSFX_PARAM_RAND_FREQ_RAISE_SHIFT) & MMSFX_PARAM_RAND_FREQ_RAISE_MASK) | '
                     f'({mm_flags(flags1)}) }},')
        count += 1
    lines.append('};')
    lines.append('')

oot = load_ids(oot_sfx)
mm = load_ids(mm_sfx)
pairs = {}
for n, v in oot.items():
    target = ALIASES.get(n, n)
    if target in mm:
        pairs.setdefault(v, mm[target])
lines.append('// { OoT sfx id, MM sfx id }, sorted by OoT id (binary searched).')
lines.append('static const u16 sOoTToMMSfxIds[][2] = {')
for v in sorted(pairs):
    lines.append(f'    {{ 0x{v:04X}, 0x{pairs[v]:04X} }},')
lines.append('};')
lines.append('')

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(lines))
print(len(pairs), 'OoT->MM pairs ->', out)
